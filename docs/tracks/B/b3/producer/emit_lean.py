"""Emit the Henon-Heiles certificate (out/hh-cert.json) as Lean data modules under
KAM/EffectiveStability/HenonHeiles/Data/.  Usage: emit_lean.py <hh-cert.json> <repo-root>.
Regenerate; never hand-edit the emitted files."""
import json, os, sys

HDR = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

public import KAM.EffectiveStability.Poly.Coeff
public import KAM.EffectiveStability.Poly.Basic

/-!
# %s (track B, B3-CERT)

%s
Generated by `docs/tracks/B/b3/producer/emit_lean.py` from `out/hh-cert.json`;
do not edit.
-/

@[expose] public noncomputable section

namespace KAM.EffectiveStability.HenonHeiles

"""
FTR = "\nend KAM.EffectiveStability.HenonHeiles\n"


def rat(s):
    return "(%s : ℚ)" % s if "/" not in s and not s.startswith("-") else "(%s : ℚ)" % s


def mono(m):
    c = m["c"]
    one = "⟨%s, %s, ⟨%s, %s⟩⟩" % (list(m["a"]), list(m["b"]), rat(c["a"]), rat(c["b"]))
    if len(one) <= 96:
        return one
    return "⟨%s, %s,\n    ⟨%s,\n     %s⟩⟩" % (list(m["a"]), list(m["b"]), rat(c["a"]), rat(c["b"]))


def poly(name, doc, P):
    out = ["/-- %s -/" % doc, "def %s : CartPolyK QSqrt2 := [" % name]
    out.append(",\n".join("  " + mono(m) for m in P))
    out.append("]\n")
    return "\n".join(out)


def write(path, title, blurb, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HDR % (title, blurb) + body + FTR)


def main():
    d = json.load(open(sys.argv[1]))
    root = os.path.join(sys.argv[2], "KAM/EffectiveStability/HenonHeiles/Data")
    write(root + "/Residual.lean", "Hénon–Heiles data: `H`, `Nact`, `P`",
          "The Hamiltonian, the action-only normal form and the residual.",
          poly("hhH", "The Hénon–Heiles Hamiltonian in Cartesian form.", d["H"]) + "\n" +
          poly("hhNact", "The normal form, in the `q` variables only.", d["Nact"]) + "\n" +
          poly("hhP", "The residual.", d["P"]))
    for k, s in enumerate(d["steps"], 1):
        write(root + "/Step%d.lean" % k, "Hénon–Heiles data: step %d" % k,
              "The generator and the output polynomial of step %d." % k,
              poly("hhGen%d" % k, "Generator of step %d." % k, s["gen"]) + "\n" +
              poly("hhOut%d" % k, "Output polynomial of step %d." % k, s["out"]))


main()
