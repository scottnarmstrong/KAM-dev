#!/usr/bin/env python3
"""S9 (RUNBOOK §7): write rebase-plan.json from the APPROVED proposal (FREEZE-PROPOSAL.md §7 rebase table and §5
characterization table at the approved commit).

usage: mk_rebase_plan.py --root <worktree> --approved <sha> [--out rebase-plan.json]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lp_freeze_lib as L  # noqa: E402

# FREEZE-PROPOSAL §7 point 3: the two characterization proofs that use a sibling characterization, inlined in the
# provider (here: the sibling's statement and proof verbatim as a private helper of the provider module).
SIBLINGS = {"KAM.Planetary.StrongAMD.sourceOscPeri_pos": "KAM.Planetary.StrongAMD.sourceOscAxis_pos",
            "KAM.Planetary.StrongAMD.orderedStrongThreshold_isLeast":
                "KAM.Planetary.StrongAMD.orderedCrossThreshold_isLeast"}
# §7 point 3: "`PlanarSafety/SourceThreshold.lean` is then empty and is deleted."
DELETE_MODULES = ["KAM.Planetary.StrongAMD.PlanarSafety.SourceThreshold"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--approved", required=True)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "rebase-plan.json"))
    a = ap.parse_args()
    root = Path(a.root).resolve()
    prop = L.git_show(root, a.approved, "docs/tracks/LP/FREEZE-PROPOSAL.md").decode()
    entries = json.loads(L.git_show(root, a.approved, "docs/tracks/LP/freeze/draft7/manifest-entries.json"))["entries"]
    by_export = {e["export"]: e for e in entries}
    sec7 = prop[prop.index("## 7. Rebase plan"):]
    defs = []
    for m in re.finditer(r"^\| `(KAM\.[\w.]+)` \| (.*?) \| `(KAM\.Frozen\.[\w.]+)\.\{([^}]*)\}` \|$", sec7, re.M):
        module, names, prefix, stems = m.group(1), re.findall(r"`([^`]+)`", m.group(2)), m.group(3), m.group(4)
        stems = [s.strip() for s in stems.split(",")]
        assert len(names) == len(stems), module
        ns = "KAM.Planetary.StrongAMD" if prefix.startswith("KAM.Frozen.Planetary.StrongAMD") else \
            "KAM.Planetary.Spatial"
        decls = []
        for n, s in zip(names, stems):
            fqn = f"{ns}.{n}"
            e = by_export[fqn]
            assert e["kind"] == "definition" and L.module_of(e["path"]) == f"{prefix}.{s}", (fqn, e["path"])
            decls.append({"name": n, "export": fqn, "frozen_module": f"{prefix}.{s}"})
        defs.append({"module": module, "delete": decls})
    sec5 = prop[prop.index("## 5. Characterization theorems"):prop.index("### 5.1")]
    chars = []
    for m in re.finditer(r"^\| `(KAM\.[\w.]+)` \| .*? \| `(KAM/Frozen/[^`]+)` \| `(KAM\.Provider\.[\w.]+)` \| "
                         r"`(KAM\.[\w.]+)` \|$", sec5, re.M):
        fqn, path, pexp, impl = m.groups()
        e = by_export[fqn]
        assert e["path"] == path and e["implementation"]["export"] == pexp, fqn
        chars.append({"export": fqn, "name": fqn.split(".")[-1], "module": impl, "provider_module":
                      e["implementation"]["module"], "provider_export": pexp, "sibling": SIBLINGS.get(fqn)})
    ndef = sum(1 for e in entries if e["kind"] == "definition")
    assert sum(len(d["delete"]) for d in defs) == ndef, (sum(len(d["delete"]) for d in defs), ndef)
    assert len(chars) == 34, len(chars)
    plan = {"_comment": ("Machine form of FREEZE-PROPOSAL §7 (rebase table) and §5 (characterizations) at the approved "
                         f"commit {a.approved} (D62); generated by mk_rebase_plan.py."),
            "approved": a.approved, "definitions": defs, "characterizations": chars,
            "delete_modules": DELETE_MODULES}
    Path(a.out).write_text(json.dumps(plan, indent=1, ensure_ascii=False) + "\n")
    print(f"{len(defs)} modules, {ndef} definitions; {len(chars)} characterizations -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
