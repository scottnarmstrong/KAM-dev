"""Order-tracked Lie series for SLG13 section 3.1 (exp(L_chi2) exp(L_chi1) H^(T)).

secular.py implements the result strictly at order two in the masses.  SLG13/GLS17 work with
numerical coefficients and describe H^(O2) as "generated by expanding the Lie series ... and by
gathering all the terms", so their numbers may contain higher-order terms.  This module computes
the same two Kolmogorov-like steps keeping every term up to a chosen mass order N (N = 2 must
agree with secular.py; N -> infinity mimics an untruncated Lie series), with the source's
truncations applied at every intermediate stage: L-degree <= 1 in the perturbation (the Kepler
part keeps K2), degree <= D in (xi, eta), |k| <= 16.  chi_2 is built from the L-linear part of
hat-H at every order < N (SLG13 eq. 7 uses hat-h^(O2)_{1, j2} as computed).

Only the secular (k = 0, L = 0) part of the result is returned.  Intermediate terms whose
harmonic cannot be brought back to k = 0 by the remaining brackets are pruned (exact).
"""
from __future__ import annotations

import time
from fractions import Fraction

import numpy as np

from sparse import SP, bracket


def _nL(bk, nvec):
    K = np.zeros((3, 3)); E = np.zeros((3, 6)); L = np.array([1, 2, 3])
    return SP(bk, K, E, L, bk.array_from(list(nvec)))


def _cap(sp, kcap):
    if len(sp) == 0:
        return sp
    return sp.select(sp.knorm() <= kcap)


def lie_secular(f, nvec, K2pp, N, D, D1=6, KF=16, KF_CHI=8, log=print, Dfinal=None):
    """Secular part through mass order N.  Dfinal (default D): degree cap of the final result;
    a term of order r is kept only up to degree Dfinal + (N - r) (exact pruning: each further
    bracket lowers the degree by at most one) and harmonic |k| <= min(16, 8 (N - r))."""
    bk = f.bk
    t0 = time.time()
    frac = lambda p, q: bk.real(Fraction(p, q))
    if Dfinal is None:
        Dfinal = D

    def reach(r):
        return min(KF, KF_CHI * max(N - r, 0))

    def dcap(r):
        return min(D, Dfinal + max(N - r, 0))

    f = f.select(f.degree() <= dcap(1))
    f0 = f.select(f.L == 0)
    kn = f0.knorm()
    f0T = f0.select((kn > 0) & (kn <= KF_CHI) & (f0.degree() <= D1))
    X1 = f0T.homological(nvec)
    H = {0: _nL(bk, nvec), 1: _cap(f, reach(1))}
    acc = {r: s.copy() for r, s in H.items()}
    T = H
    for s in range(1, N + 1):
        Tn = {}
        for r, sp in T.items():
            if r + 1 > N or len(sp) == 0:
                continue
            b = bracket(X1, sp, None, dcap(r + 1), 1, None, kcap=reach(r + 1))
            Tn[r + 1] = (Tn[r + 1] + b) if (r + 1) in Tn else b
        if s == 1:
            k2 = _cap(X1.bracket_K2(K2pp), reach(1))
            k2 = k2.select(k2.degree() <= dcap(1))
            Tn[1] = Tn[1] + k2 if 1 in Tn else k2
        Tn = {r: sp.scaled(frac(1, s)) for r, sp in Tn.items() if len(sp)}
        for r, sp in Tn.items():
            acc[r] = acc[r] + sp if r in acc else sp
        T = Tn
        log(f'    chi1 series s={s}: ' + ', '.join(f'o{r}:{len(sp)}' for r, sp in sorted(Tn.items()))
            + f'  ({time.time()-t0:.1f}s)')
        if not T:
            break
    # chi_2 from the L-linear part of hat-H, orders 1..N-1
    X2 = {}
    for r in range(1, N):
        if r not in acc:
            continue
        h = acc[r]
        h1 = h.select(h.L > 0)
        k1 = h1.knorm()
        h1T = h1.select((k1 > 0) & (k1 <= KF_CHI) & (h1.degree() <= D1))
        if len(h1T):
            X2[r] = h1T.homological(nvec)
    total = {r: sp.copy() for r, sp in acc.items()}
    U = acc
    for s in range(1, N + 1):
        Un = {}
        for m, x2 in X2.items():
            for r, sp in U.items():
                if m + r > N or len(sp) == 0:
                    continue
                b = bracket(x2, sp, None, dcap(m + r), 1, None, kcap=reach(m + r))
                Un[m + r] = (Un[m + r] + b) if (m + r) in Un else b
        Un = {r: sp.scaled(frac(1, s)) for r, sp in Un.items() if len(sp)}
        for r, sp in Un.items():
            total[r] = total[r] + sp if r in total else sp
        U = Un
        log(f'    chi2 series s={s}: ' + ', '.join(f'o{r}:{len(sp)}' for r, sp in sorted(Un.items()))
            + f'  ({time.time()-t0:.1f}s)')
        if not U:
            break
    out = {}
    for r, sp in total.items():
        sec = sp.select(sp.is_secular() & (sp.L == 0) & (sp.degree() <= Dfinal))
        if len(sec):
            out[r] = sec
    return out
