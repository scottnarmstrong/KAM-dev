#!/usr/bin/env python3
"""N7 ledger emitter (T2-CONF): Lean data and check modules under KAM/EffectiveStability/SJSU/Ledger.

Every module: copyright header, `module`, `public import`s, docstring, `@[expose] public section`,
namespace KAM.EffectiveStability.SJSU; lines <= 100 characters; files <= 1500 lines (data split into
parts with a facade).  Literal naturals are explicit Nat.add / Nat.shiftLeft trees of 288-bit chunks
in sub-definitions of <= 256 chunks (SR-6).
Usage: python3 emit.py F [--small]   (the observables; more stages to follow)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from fractions import Fraction as Fr
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import fobs  # noqa: E402

HEADER = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

"""
NS = 'KAM.EffectiveStability.SJSU'
MAXL = 100
MAXLINES = 1400


def rat(q: Fr) -> str:
    q = Fr(q)
    if q.denominator == 1:
        return f'({q.numerator} : ℚ)'
    return f'({q.numerator} / {q.denominator} : ℚ)'


def wrap_tokens(head, toks, indent='  '):
    lines, cur = [], head
    for t in toks:
        if len(cur) + 1 + len(t) > MAXL:
            lines.append(cur)
            cur = indent + t
        else:
            cur = cur + (' ' if cur and not cur.endswith('[') else '') + t
    lines.append(cur)
    return lines


def module_text(imports, doc, body_lines):
    out = HEADER
    out += ''.join(f'public import {m}\n' for m in imports)
    out += f'\n/-!\n{doc}\n-/\n\n@[expose] public section\n\nnamespace {NS}\n\nopen KAM.EffectiveStability.Tube\n\n'
    out += '\n'.join(body_lines)
    out += f'\n\nend {NS}\n\nend\n'
    return out


CHUNK = 48


def spd_lines(name, C, q, mant):
    """the chunks as separate typed definitions (each elaborates alone), then the model"""
    ents = [f'(({c}, {r}), {m})' for (c, r), m in sorted(mant.items(), key=lambda x: (x[0][1], x[0][0]))]
    chunks = [ents[i:i + CHUNK] for i in range(0, len(ents), CHUNK)] or [[]]
    lines = []
    cnames = []
    for ci, ch in enumerate(chunks):
        cn = f'{name}_e{ci}'
        cnames.append(cn)
        toks = [e + ',' for e in ch]
        if toks:
            toks[-1] = toks[-1][:-1] + ']'
        else:
            toks = [']']
        lines += wrap_tokens(f'def {cn} : List ((ℕ × ℕ) × ℤ) := [', toks, '  ')
        lines.append('')
    lines += [f'/-- A sparse literal model. -/', f'def {name} : SpD where', f'  C := {C}', '  par := false',
              f'  q := {rat(q)}']
    lines += wrap_tokens('  es :=', [c + (' ++' if i < len(cnames) - 1 else '') for i, c in enumerate(cnames)],
                         '    ')
    lines.append('')
    return lines


def emit_F(small, outdir: Path, w, S, b):
    Fs, cf = fobs.load(small)
    sub = outdir / 'F'
    sub.mkdir(parents=True, exist_ok=True)
    parts, cur, cnt = [], [], 0
    names = {}
    for j, Fj in enumerate(Fs):
        for s, (q, mant) in sorted(Fj.items()):
            nm = f'F_{j}_{s[0]}_{s[1]}_{s[2]}'
            names[(j, s)] = nm
            ls = spd_lines(nm, cf, q, mant)
            if cnt + len(ls) > MAXLINES and cur:
                parts.append(cur)
                cur, cnt = [], 0
            cur += ls
            cnt += len(ls)
    if cur:
        parts.append(cur)
    mods = []
    for i, ls in enumerate(parts):
        mod = f'KAM.EffectiveStability.SJSU.Ledger.F.Part{i}'
        (sub / f'Part{i}.lean').write_text(module_text(
            ['KAM.EffectiveStability.Tube.Engine.Sparse'],
            f'# Literal observables, part {i} (T2-CONF; generated by scripts/sjsu/ledger/emit.py)\n\n'
            'Sparse literal models of the u-coefficients of the observables `f_j` (see `Ledger/F.lean`).',
            ls))
        mods.append(mod)
    body = ['/-- The packing parameters of the bracket stage (slot width, stride, digit width). -/',
            f'def Fprm : Prm := ⟨{w}, {S}, {b}⟩', '']
    for j in range(3):
        ents = [f'(({s[0]}, {s[1]}, {s[2]}), {names[(j, s)]}),' for s in sorted(Fs[j])]
        ents[-1] = ents[-1][:-1] + ']'
        body.append(f'/-- The literal observable `f_{j}`: u-monomial ↦ sparse coefficient model. -/')
        body += wrap_tokens(f'def Ftab{j} : List ((ℕ × ℕ × ℕ) × SpD) := [', ents, '  ')
        body.append('')
    body += ['/-- The literal observables by index (`j ≥ 3`: empty). -/',
             'def Ftab (j : ℕ) : List ((ℕ × ℕ × ℕ) × SpD) :=',
             '  if j = 0 then Ftab0 else if j = 1 then Ftab1 else if j = 2 then Ftab2 else []']
    (outdir / 'F.lean').write_text(module_text(
        mods, '# The literal observables of T2-CONF (generated by scripts/sjsu/ledger/emit.py)\n\n'
        'F-v1.json even parts (producer run sr-vp-L8), pruned at `|a| (2·10⁻⁶)^|s| < 10⁻²¹` and rounded to\n'
        '80 bits per u-monomial (`scripts/sjsu/ledger/fobs.py`): the rounded, pruned literal IS the\n'
        'observable. `Ftab j` lists `(s, F_{j,s})`; `f_j(u, φ) = Σ_s u^s (F_{j,s}.opd w S).eval S φ`.', body))
    n = sum(len(m) for Fj in Fs for _, m in Fj.values())
    print(f'F: {len(names)} models, {n} entries, {len(parts)} parts')
    return mods + ['KAM.EffectiveStability.SJSU.Ledger.F']


LEDGER = 'KAM.EffectiveStability.SJSU.Ledger'


def module_path(outdir: Path, mod: str) -> Path:
    """The file of a Ledger module under the output directory `outdir` (= the `Ledger` directory)."""
    assert mod == LEDGER or mod.startswith(LEDGER + '.'), mod
    rel = mod[len(LEDGER) + 1:]
    return outdir / (rel.replace('.', '/') + '.lean')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('stage', choices=['F'])
    ap.add_argument('--small', action='store_true')
    ap.add_argument('--w', type=int, default=448)
    ap.add_argument('--S', type=int, default=139)
    ap.add_argument('--b', type=int, default=82)
    ap.add_argument('--outdir', help='write the Ledger tree (and its manifest) here instead, e.g. to '
                                     'regenerate into a scratch directory for a byte comparison')
    args = ap.parse_args()
    outdir = ROOT / 'KAM/EffectiveStability/SJSU/Ledger'
    if args.small:
        outdir = ROOT / '.drafts/g2/scratch/n7/ledger-small/SJSU/Ledger'
    if args.outdir:
        outdir = Path(args.outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)
    mods = emit_F(args.small, outdir, args.w, args.S, args.b)
    # hash exactly the files this run wrote (audit N7-N8-1 N1: the small run hashed production paths)
    missing = [m for m in mods if not module_path(outdir, m).exists()]
    if missing:
        raise SystemExit(f'emit: modules not written under {outdir}: {missing}')
    man = {m: hashlib.sha256(module_path(outdir, m).read_bytes()).hexdigest() for m in mods}
    name = 'manifest-F-small.json' if args.small else 'manifest-F.json'
    mdir = outdir if args.outdir else HERE
    (mdir / name).write_text(json.dumps(man, indent=1) + '\n')
    print(f'manifest: {len(man)} modules -> {mdir / name}')


if __name__ == '__main__':
    sys.exit(main())
