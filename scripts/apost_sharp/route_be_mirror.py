#!/usr/bin/env python3
"""V2-ENERGY step 4: exact mirror of `RunBWit.numE` and the comparison of y0 = M s_N with y0 = dh s_N.

Untrusted tooling.  Two jobs:

* `--emit FILE` writes the Lean cross-language test KAM/CertificateSharp/V2/Tests/RouteBEMirror.lean: the constants of
  `stepConstsB` evaluated here in exact rationals (route_b_lean_mirror.py, which parses the Lean definitions) are compared
  with Lean's `StepBQ` values at the toy witnesses, by `decide +kernel`, through a fingerprint (numerator and denominator
  modulo a 61-bit prime), since the rationals do not fit the line limit.  The verdicts of `okB` are compared too.
* the default run re-derives that file and compares it with the checkout (exit 1 on drift), then, on the same
  certificates (lunar N = 65, LG00 T'), evaluates `routeBOk` in exact rationals at a short rational X* just below the
  threshold with y0 = dh s_N, for both values of y0, with classical constants.

Usage: python3 -B -I scripts/apost_sharp/route_be_mirror.py [--emit FILE] [--json OUT]
"""
import json, math, os, sys
from fractions import Fraction as F

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import route_b_lean_mirror as RB   # noqa: E402

LEAN = os.path.join(ROOT, "KAM/CertificateSharp/V2/Tests/RouteBEMirror.lean")
PRIME = 2305843009213693951        # 2^61 - 1
CONSTS = ("sC0", "sCDK", "sQ", "sCab", "sBloc", "sCnu")

# toyB and toyRefinedBWit (KAM/CertificateSharp/V2/Tests/RouteBToy.lean, Tests/Refined.lean)
P = dict(rho=F(1), rhoInf=F(1, 100), M=F(297, 100), sK=F(297, 100), sB=F(297, 100), sT=F(297, 100), mu=F(1, 100),
         gamma=F(1, 42), som=F(3), nu=F(49, 100), boxUp=F(1, 2))
R = dict(dh=F(2), dx=F(101, 100), d2x=F(1, 100), d2h=F(101, 100), bL=F(101, 100), bN=F(101, 100), bNt=F(101, 100))
W = dict(Xs=F(1, 10 ** 20), bF=F(1, 10 ** 15), kp=2, a=F(2), ybar=F(1, 2), th=F(1, 16), ts=F(1, 10), lam0=F(393, 100000),
         lamW0=F(389, 100000), ePer0=F(389, 100000), c=[F(1, 50), F(93, 1000)], c_=[F(93, 1000), F(11, 125)],
         cbar=[F(171, 1000), F(27, 200)], ctail=F(11, 125), cbtail=F(14, 125), sB=F(777, 250), sT=F(777, 250),
         sLt=F(2121, 2000), sN=F(2121, 2000), sNt=F(2121, 2000))


def getd(L, d):
    return lambda s: L[s] if s < len(L) else d


def num_of(w, R, Mh1):
    """`RunBWit.num` (Mh1 = M) and `RunBWit.numE`, at the numbers of the refined run."""
    return RB.NumB(n=2, τ=F(1), ρ=P["rho"], ρinf=P["rhoInf"], γb=P["gamma"], M1=R["dx"], M2=R["d2x"], cTh=2 * R["dx"],
                   cDTh=2 * R["d2x"], sK=P["sK"] - P["mu"] / 2, sLt=w["sLt"], sB=w["sB"], sN=w["sN"], sNt=w["sNt"],
                   sT=w["sT"], ts=w["ts"], bF=w["bF"], θ=w["th"], θξ=F(1, 8), θΩ=F(1, 8), q=F(1, 8), θN=F(1, 8),
                   θω=F(1, 8), a=w["a"], ybar=w["ybar"], kp=w["kp"], c=getd(w["c"], w["ctail"]),
                   c_=getd(w["c_"], w["ctail"]), cbar=getd(w["cbar"], w["cbtail"]), ctail=w["ctail"], cbtail=w["cbtail"],
                   lam0=w["lam0"], lamW0=w["lamW0"], ePer0=w["ePer0"], iso=True, Θ=P["som"] * P["boxUp"],
                   y0=Mh1 * w["sN"], Mh2=R["d2h"])


def verdict(N, R, Xs):
    I = dict(iLt=R["bL"], iN=R["bN"], iNt=R["bNt"])
    return not RB.routeBOk(N, RB.capB(N, P["sT"], P["mu"], P["nu"]), RB.initB(I, P["sK"], P["sB"], P["mu"]), P["mu"] / 2, Xs)


def fp(x):
    x = F(x)
    return x.numerator % PRIME, x.denominator % PRIME


def emit():
    gain = dict(W, Xs=F(27, 10 ** 6), bF=F(1, 10 ** 4))
    cases = [("Ord", "toyRefinedBWit", W), ("Gain", "toyBGain", gain)]
    out = ['''/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

public import KAM.CertificateSharp.V2.Tests.RouteBE

/-!
# Cross-language test of `RunBWit.numE` (generated)

Generated by `scripts/apost_sharp/route_be_mirror.py --emit`. The Python mirror evaluates the
constants of `stepConstsB` and the verdicts of `okB` in exact rationals, from the parsed Lean
definitions; here the kernel compares them with `StepBQ` at the same witnesses, for `y₀ = dh s_N`
(`numE`) and `y₀ = M s_N` (`num`). A rational is compared through `fp`: its numerator and
denominator modulo `2^61 - 1`.
-/

@[expose] public section

namespace KAM.CertificateSharp.V2.BEMirror

open KAM.Certificate KAM.Sharp2.RouteB

/-- The fingerprint of a rational. -/
def fp (x : ℚ) : ℤ × ℕ := (x.num % 2305843009213693951, x.den % 2305843009213693951)

/-- The numbers of a run, by `dh` or by `M`. -/
def run (w : RefinedBWit) (e : Bool) : NumBQ :=
  if e then w.numE toyB.params toyB.freqBox else w.num toyB.params toyB.freqBox

/-- The verdict of `okB`. -/
def ok (w : RefinedBWit) (e : Bool) : Bool :=
  let p := toyB.params
  (run w e).okB 2 ((run w e).capBQ p.σT p.μ p.nuRay)
    (NumBQ.initBQ w.R.bL w.R.bN w.R.bNt p.σK p.σB p.μ) (p.μ / 2) w.core.Xs
''']
    for tag, name, w in cases:
        for e, lab, Mh1 in ((True, "E", R["dh"]), (False, "M", P["M"])):
            N = num_of(w, R, Mh1)
            out.append("/-- `y₀` of `%s`, `%s`. -/\ntheorem y0_%s%s : fp (run %s %s).y0 = (%d, %d) := by decide +kernel\n" % (
                name, "numE" if e else "num", tag, lab, name, "true" if e else "false", *fp(N.y0)))
            for s in range(w["kp"] + 1):
                k = RB.CM.consts(N.inp(s))
                for c in CONSTS:
                    out.append("theorem %s_%s%s_%d :\n    fp (((run %s %s).inp 2 %d).%s) =\n      (%d, %d) := by\n  decide +kernel\n" % (
                        c, tag, lab, s, name, "true" if e else "false", s, c, *fp(k[c])))
            out.append("/-- The verdict of `okB` agrees. -/\ntheorem ok_%s%s : ok %s %s = %s := by decide +kernel\n" % (
                tag, lab, name, "true" if e else "false", "true" if verdict(N, R, w["Xs"]) else "false"))
    out.append("end KAM.CertificateSharp.V2.BEMirror\n\nend\n")
    return "\n".join(out)


def compare():
    import structured_b as SB
    import energy_row as ER
    RBm, T2 = SB.setup_mirror()
    res = {}
    data = [("lower", SB.lunar_bounds("lower")), ("upper", SB.lunar_bounds("upper")), ("tp", SB.lg00_bounds())]
    for tag, B in data:
        if tag == "tp":
            B, pkg = ER.lg00_tp(B)
        else:
            pkg = SB.lunar_pkg(tag, B)
        p, Rc = pkg["p"], pkg["R"]
        kp = 5
        # the float threshold at dh, then a short rational below it
        N, I, sig = SB.run_inputs(pkg, "classical", kp, RB, T2)
        N.y0 = Rc["dh"] * N.sN
        lx = SB.threshold(N, I, sig, RB, iters=30)
        e10 = math.floor(lx) - 2
        Xs = F(int(10 ** (lx - e10))) * F(10) ** e10
        row = dict(Xs=str(Xs))
        for name, Mh1 in (("dh", Rc["dh"]), ("M", p["M"])):
            N, I, sig = SB.run_inputs(pkg, "classical", kp, RB, T2, exact=True)
            N.y0 = Mh1 * N.sN
            fails = SB.ok_at(N, I, sig, Xs, RB)
            row[name] = dict(routeBOk=not fails, fails=fails[:6], log10_e=RB.log10(
                p["gamma"] ** 4 * RB.ipow(N.ρ, 4 * N.τ) / RB.c1B(N, I, Xs)))
        res[tag] = row
        print("%-6s X* = %s: y0 = dh s_N routeBOk %s (log10 e* %.3f); y0 = M s_N routeBOk %s %s" % (
            tag, Xs, row["dh"]["routeBOk"], row["dh"]["log10_e"], row["M"]["routeBOk"], row["M"]["fails"]), flush=True)
    return res


def main():
    txt = emit()
    if "--emit" in sys.argv:
        open(sys.argv[sys.argv.index("--emit") + 1], "w", encoding="utf-8").write(txt)
        print("emitted", len(txt.splitlines()), "lines")
        return 0
    same = os.path.exists(LEAN) and open(LEAN, encoding="utf-8").read() == txt
    print("Lean cross-language test up to date:", same)
    res = compare()
    if "--json" in sys.argv:
        json.dump(res, open(sys.argv[sys.argv.index("--json") + 1], "w"), indent=1, default=str)
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
