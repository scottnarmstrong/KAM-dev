#!/usr/bin/env python3
"""SHARP2-C6B: generate KAM/CertificateSharp/V2/StepBQ.lean, the exact rational mirror of the constants of route B.

Reads the helper definitions of `KAM.Sharp2.stepConstsB` (KAM/Sharp2/ModConstantsB/Data.lean, one `def sX (p : StepInB) :
ℝ := ...` per `let`; `stepConstsB_eq` is rfl) and writes, for each, the same body over `ℚ` with a natural exponent `κ`
(`StepBQ.sX`) and the cast lemma `StepBQ.cast_sX : KAM.Sharp2.sX p.toB = (p.sX : ℝ)`. The bodies are copied textually;
only the type ascription `(p.n : ℝ)` becomes `(p.n : ℚ)`.

Usage: python3 -I scripts/apost_sharp/gen_stepbq.py   (rewrites the Lean file; untrusted tooling)
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = open(os.path.join(ROOT, "KAM/Sharp2/ModConstantsB/Data.lean"), encoding="utf-8").read()
OUT = os.path.join(ROOT, "KAM/CertificateSharp/V2/StepBQ.lean")

defs = []
for m in re.finditer(r"def (\w+) \(p : StepInB\) : ℝ :=\n((?:  .*\n)+)", SRC):
    defs.append((m.group(1), m.group(2).rstrip("\n")))
names = [d[0] for d in defs]

QFIELDS = ["M1", "M2", "cTh", "cDTh", "sK", "sLt", "sB", "sN", "sNt", "sT", "ts", "bF", "c", "c1", "cavg", "θ", "θξ",
           "θΩ", "q", "θN", "θω", "a", "lam", "γb", "δ"]

HEADER = '''/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

public import KAM.Sharp2.ModConstantsB

/-!
# Exact rational mirror of the constants of route B

Every constant of the repaired modified step `KAM.Sharp2.stepConstsB` is a rational at rational
inputs with a natural exponent `κ`. `StepBQ` is the rational record, `StepBQ.toB` its real image,
and `StepBQ.sX` the mirror of each helper `KAM.Sharp2.sX` of `ModConstantsB/Data.lean` (one per
`let` of `stepConstsB`; `stepConstsB_eq` is `rfl`), with `StepBQ.cast_sX : sX p.toB = (p.sX : ℝ)`.
`StepBQ.condB` is the Boolean form of `stepCondB`, and `StepBQ.condB_sound` its soundness.

The isoenergetic, stage-0 and L10 branches are kept: `iso`, `stage0`, `selfcons` are fields.
Generated by `scripts/apost_sharp/gen_stepbq.py` from the helper definitions (bodies copied).
-/

@[expose] public section

namespace KAM.CertificateSharp.V2

/-- The rational inputs of one modified step of route B, with a natural exponent `κ`. -/
structure StepBQ where
  n : ℕ
  κ : ℕ
'''



TAIL = """/-! ### The step conditions -/

/-- `stepCondB` over `ℚ`. -/
def condB (p : StepBQ) (X : ℚ) : Bool :=
  decide (max 1 (p.sB ^ 2) * sCΩ p * sg p * X ≤ p.q) && decide (sCDE p * sg p * X ≤ p.n) &&
    decide (sCxiL p * X ≤ p.θξ) && decide (sCΩ p * sCgL p * X ≤ p.θΩ) &&
    decide (sCKt p * (sg p * p.δ) * X ≤ 1) && decide (sCDLt p * sg p * X ≤ p.θ * p.sK) &&
    decide (sCDLtT p * sg p * X ≤ p.θ * p.sLt) && decide (p.sB * sCG p * sCDK p * X ≤ p.θ) &&
    decide (sBsup p * X ≤ p.ts) && decide (sBloc p * X ≤ p.bF) &&
    (!p.iso || decide (sC0 p * (sg p * p.δ) * X ≤ p.θω)) &&
    (!p.selfcons || (decide (sCNbT p * sCEL p * X ≤ p.θN) &&
      decide (max 1 (p.sB ^ 2) * (1 + p.n * p.θξ) ^ 2 * sCΩ p * sQtN p * sg p * X ^ 2 ≤ p.q)))

/-- **`condB` gives the step conditions.** -/
theorem condB_sound {X : ℚ} (h : p.condB X = true) : KAM.Sharp2.stepCondB p.toB X := by
  rw [KAM.Sharp2.stepCondB_eq]
  simp only [KAM.Sharp2.condH, cast_sCΩ, cast_sg, cast_sCDE, cast_sCxiL, cast_sCgL, cast_sCKt,
    cast_sCDLt, cast_sCDLtT, cast_sCG, cast_sCDK, cast_sBsup, cast_sBloc, cast_sC0, cast_sCNbT,
    cast_sCEL, cast_sQtN]
  simp only [toB]
  simp only [condB, Bool.and_eq_true, decide_eq_true_eq, Bool.or_eq_true, Bool.not_eq_true']
    at h
  obtain ⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨⟨h1, h2⟩, h3⟩, h4⟩, h5⟩, h6⟩, h7⟩, h8⟩, h9⟩, h10⟩, h11⟩, h12⟩ := h
  refine ⟨by exact_mod_cast h1, by exact_mod_cast h2, by exact_mod_cast h3, by exact_mod_cast h4,
    by exact_mod_cast h5, by exact_mod_cast h6, by exact_mod_cast h7, by exact_mod_cast h8,
    by exact_mod_cast h9, by exact_mod_cast h10, fun hi => ?_, fun hs => ?_⟩
  · rcases h11 with h11 | h11
    · rw [hi] at h11; exact absurd h11 (by decide)
    · exact_mod_cast h11
  · rcases h12 with h12 | ⟨h12, h13⟩
    · rw [hs] at h12; exact absurd h12 (by decide)
    · exact ⟨by exact_mod_cast h12, by exact_mod_cast h13⟩

end StepBQ

end KAM.CertificateSharp.V2

end
"""


def body_q(b):
    return b.replace("(p.n : ℝ)", "(p.n : ℚ)")


def deps(b, me):
    return [x for x in names if x != me and re.search(r"(?<![\w.])" + re.escape(x) + r" p\b", b)]


out = [HEADER]
for f in QFIELDS:
    out.append("  %s : ℚ\n" % f)
out.append("  selfcons : Bool\n  stage0 : Bool\n  ePer : ℚ\n  iso : Bool\n  Θ : ℚ\n  y0 : ℚ\n  Mh2 : ℚ\n  lamW : ℚ\n")
out.append("\nnamespace StepBQ\n\n")
out.append("/-- The real record. -/\nnoncomputable def toB (p : StepBQ) : KAM.Sharp2.StepInB :=\n")
fl = ["n := p.n", "κ := p.κ"] + ["%s := p.%s" % (f, f) for f in QFIELDS] + \
     ["selfcons := p.selfcons", "stage0 := p.stage0", "ePer := p.ePer", "iso := p.iso", "Θ := p.Θ", "y0 := p.y0",
      "Mh2 := p.Mh2", "lamW := p.lamW"]
lines, cur = [], "  {"
for i, f in enumerate(fl):
    piece = " " + f + ("," if i < len(fl) - 1 else " }")
    if len(cur) + len(piece) > 100:
        lines.append(cur.rstrip())
        cur = "   " + piece
    else:
        cur += piece
lines.append(cur)
out.append("\n".join(lines) + "\n\n")
out.append("/-! ### The constants -/\n\n")
for nm, b in defs:
    out.append("def %s (p : StepBQ) : ℚ :=\n%s\n\n" % (nm, body_q(b)))
out.append("/-! ### The casts -/\n\nvariable {p : StepBQ}\n\n")
for nm, b in defs:
    ds = deps(b, nm)
    simp1 = ", ".join(["KAM.Sharp2." + nm, "StepBQ." + nm] + ["cast_" + d for d in ds])
    has_if = "if " in b
    pre = "  simp only [%s]\n" % simp1
    # wrap the simp line at 100 characters
    if len(pre) > 101:
        parts = simp1.split(", ")
        cur = "  simp only ["
        ls = []
        for i, pt in enumerate(parts):
            piece = pt + (", " if i < len(parts) - 1 else "]")
            if len(cur) + len(piece) > 100:
                ls.append(cur.rstrip())
                cur = "    " + piece
            else:
                cur += piece
        ls.append(cur)
        pre = "\n".join(ls) + "\n"
    if "^ p.κ" in b:
        tac = pre + "  simp only [toB, Real.rpow_natCast]\n"
    elif re.search(r"(?<![\w])p\.", b):
        tac = pre + "  simp only [toB]\n"
    else:
        tac = pre
    tac += ("  push_cast [apply_ite (Rat.cast : ℚ → ℝ)]\n  try rfl\n" if has_if else "  push_cast\n  try rfl\n")
    out.append("theorem cast_%s : KAM.Sharp2.%s p.toB = (p.%s : ℝ) := by\n%s\n" % (nm, nm, nm, tac))
out.append(TAIL)
open(OUT, "w", encoding="utf-8").write("".join(out))
print("wrote", OUT, len(defs), "helpers")
