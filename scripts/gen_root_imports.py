#!/usr/bin/env python3
"""Generate (or check) the library roots: the core root `KAM.lean` with its parts `KAM/Root/*.lean`,
and one root `<Lib>.lean` with parts `<Lib>/**.lean` per certificate application (decision D51).

Usage:
  scripts/gen_root_imports.py              rewrite every root, its parts, and the generated block of
                                           lakefile.lean
  scripts/gen_root_imports.py --check      exit 1 if a module is covered by no root or by two, if an
                                           import crosses libraries the wrong way, or if any generated
                                           file is out of date
  scripts/gen_root_imports.py --lib-of X…  print `<module or path> <library>` for each module name or
                                           `.lean` path X
  scripts/gen_root_imports.py --modules L  print the modules of library L (`KAM` for the core)
  scripts/gen_root_imports.py --generated-paths
                                           print the existing generated paths (roots, part
                                           directories, lakefile.lean), for staging them in git

Which library owns a module is declared in `scripts/build_roots.json`: a module belongs to the
application whose prefix it extends, otherwise to the core library `KAM`. A plain `lake build`
builds only the core (the lakefile's default library has `roots := #[`KAM]` and no submodule glob);
an application builds only through `lake build <Lib>`. The check rejects a module claimed by two
applications, a module under an `application_only` prefix (certificate data) that no application
claims, a core module that imports an application module, and an application module that imports
a module of another application it does not require. So a new module is never silently left out
of every root, and a plain `lake build` never reaches certificate data.

Every module of a library is imported by its root, except the frozen theorem anchors in state
`DRAFT_SORRY` and their provider modules: the frozen-anchor quarantine forbids every other module,
the roots included, from importing them. Each library builds them instead as extra `.one` globs,
listed in the generated block of `lakefile.lean`. No module may import a root or a part.

The imports are split into parts so that no generated file exceeds the 1500-line limit: one part
per top-level area `KAM.<Area>` (`KAM.Root.<Area>` for the core, `<Lib>.<Area>` for an application),
and an area with more than `LIMIT` modules is split further by its next name component (with `Top`
for the modules directly under the area). The grouping follows the module names, so adding a
module changes only its own part. Every generated file has the module layout of AGENTS.md rule 3
(copyright, `module`, imports, module docstring, `public section`).
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "scripts" / "build_roots.json"
LAKEFILE = ROOT / "lakefile.lean"
LIB = "KAM"
LIMIT = 1000
BLOCK_BEGIN = "-- BEGIN GENERATED BLOCK (scripts/gen_root_imports.py; do not edit by hand)"
BLOCK_END = "-- END GENERATED BLOCK"

HEADER = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module
"""

DOC = """
/-!
# KAM

Root of the KAM formalization. This file imports the generated parts `KAM.Root.*`, which together
import every core module of the library: every module except the certificate applications (opt-in
libraries with their own roots, `scripts/build_roots.json`) and the frozen theorem anchors that are
still `DRAFT_SORRY` and their provider modules, which the frozen-anchor quarantine forbids
importing; a plain `lake build` still compiles those through the library's globs. It is generated by
`scripts/gen_root_imports.py`; do not edit it by hand, and never import it.
-/
"""

APP_DOC = (
    "Root of the certificate application `{lib}`: {title}. An opt-in library (decision D51): a plain "
    "`lake build` does not build it; `lake build {lib}` does, through the serial capped driver. This "
    "file imports the generated parts `{lib}.*`, which together import every module that "
    "`scripts/build_roots.json` assigns to `{lib}`, except the frozen theorem anchors that are still "
    "`DRAFT_SORRY` and their provider modules (built through the library's globs). It is generated by "
    "`scripts/gen_root_imports.py`; do not edit it by hand, and never import it.")


def app_doc(lib: str, title: str) -> str:
    body = textwrap.fill(APP_DOC.format(lib=lib, title=title), width=100, break_long_words=False,
                         break_on_hyphens=False)
    return f"\n/-!\n# {lib}\n\n{body}\n-/\n"

# Every generated file ends with `public section`, as AGENTS.md rule 3 asks of every module.
SECTION = "\npublic section\n"

PART_DOC = """
/-!
# Root part `{name}`

Part of the generated root `{root}.lean`. It imports
{area},
except those that the root skips. Generated by `scripts/gen_root_imports.py`; do not edit it by
hand, and never import it.
-/
"""


def _helpers():
    spec = importlib.util.spec_from_file_location("check_lean_modules", ROOT / "scripts" / "check_lean_modules.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def load_config() -> dict:
    return json.loads(CONFIG.read_text(encoding="utf-8"))


def applications(cfg: dict | None = None) -> list[dict]:
    return (cfg or load_config())["applications"]


def libraries(cfg: dict | None = None) -> list[str]:
    """The core library first, then the applications in the order of the mapping."""
    cfg = cfg or load_config()
    return [cfg["core"]["lib"]] + [a["lib"] for a in cfg["applications"]]


def module_name(path: Path) -> str:
    return ".".join(path.relative_to(ROOT).with_suffix("").parts)


def all_modules() -> list[str]:
    """Every module under `KAM/` except the core root's generated parts."""
    return [module_name(p) for p in sorted((ROOT / LIB).rglob("*.lean"))
            if not (len(p.relative_to(ROOT).parts) > 1 and p.relative_to(ROOT).parts[1] == "Root")]


def extends(module: str, prefix: str) -> bool:
    return module == prefix or module.startswith(prefix + ".")


def owners(module: str, cfg: dict) -> list[str]:
    """The applications whose prefixes cover `module`."""
    return [a["lib"] for a in cfg["applications"] if any(extends(module, p) for p in a["prefixes"])]


def library_of(module: str, cfg: dict | None = None) -> str:
    """The library that builds `module` (the first claimant if the mapping is ambiguous)."""
    cfg = cfg or load_config()
    found = owners(module, cfg)
    return found[0] if found else cfg["core"]["lib"]


def quarantined() -> set[str]:
    """Module names of DRAFT_SORRY theorem anchors and of their provider modules."""
    manifest = ROOT / "manifest" / "frozen-anchors.json"
    out: set[str] = set()
    for anchor in json.loads(manifest.read_text(encoding="utf-8")).get("anchors", []):
        if anchor.get("kind") == "theorem" and anchor.get("state") == "DRAFT_SORRY":
            out.add(".".join(Path(anchor["path"]).with_suffix("").parts))
            out.add(anchor["implementation"]["module"])
    return out


def classify(cfg: dict | None = None) -> tuple[dict[str, str], list[str]]:
    """({module: library}, errors) for every module under KAM/."""
    cfg = cfg or load_config()
    core = cfg["core"]["lib"]
    libs = libraries(cfg)
    errors: list[str] = []
    if len(set(libs)) != len(libs):
        errors.append(f"library names repeat in {CONFIG.relative_to(ROOT)}: {libs}")
    for app in cfg["applications"]:
        for req in app.get("requires", []):
            if req not in libs or req == core:
                errors.append(f"{app['lib']} requires {req}, which is not an application")
    mods = all_modules()
    lib_of: dict[str, str] = {}
    for m in mods:
        found = owners(m, cfg)
        if len(found) > 1:
            errors.append(f"module {m} is covered by two roots ({', '.join(found)})")
        if not found and any(extends(m, p) for p in cfg.get("application_only", [])):
            errors.append(f"module {m} is covered by no root: it lies under an application_only prefix "
                          f"but no application claims it")
        lib_of[m] = found[0] if found else core
    for app in cfg["applications"]:
        for p in app["prefixes"]:
            if not any(extends(m, p) for m in mods) and not any(
                    extends(p, q) for q in cfg.get("application_only", [])):
                # A data prefix may precede its data (a branch not landed yet); any other dead prefix
                # is a typo that would let a module fall back to the core silently.
                errors.append(f"{app['lib']}: prefix {p} matches no module")
    helpers = _helpers()
    requires = {a["lib"]: set(a.get("requires", [])) for a in cfg["applications"]}
    for m in mods:
        lib = lib_of[m]
        text = helpers.code_mask((ROOT / Path(*m.split("."))).with_suffix(".lean").read_text(encoding="utf-8"))
        for dep in helpers.IMPORT.findall(text):
            if dep not in lib_of or lib_of[dep] in (core, lib) or lib_of[dep] in requires.get(lib, ()):
                continue
            kind = "core module" if lib == core else f"{lib} module"
            errors.append(f"{kind} {m} imports {dep}, a module of the application {lib_of[dep]}")
    return lib_of, errors


def split(base: list[str], prefix: list[str], names: list[str]) -> dict[str, list[str]]:
    """Parts for the modules `names`, all of which start with `KAM.<prefix>`: one part named
    `<base>.<prefix>` if there are at most `LIMIT`, else one per next name component."""
    if len(names) <= LIMIT:
        return {".".join(base + prefix): names}
    groups: dict[str, list[str]] = {}
    depth = len(prefix) + 1
    for n in names:
        comps = n.split(".")
        groups.setdefault(comps[depth] if len(comps) > depth + 1 else "Top", []).append(n)
    out: dict[str, list[str]] = {}
    for key, group in sorted(groups.items()):
        out.update(split(base, prefix + [key], group) if key != "Top" else {".".join(base + prefix + ["Top"]): group})
    return out


def parts(base: list[str], names: list[str]) -> dict[str, list[str]]:
    areas: dict[str, list[str]] = {}
    for n in names:
        comps = n.split(".")
        areas.setdefault(comps[1] if len(comps) > 2 else "Top", []).append(n)
    out: dict[str, list[str]] = {}
    for area, group in sorted(areas.items()):
        out.update(split(base, [area], group))
    return out


def path_of(module: str) -> Path:
    return ROOT / Path(*module.split(".")).with_suffix(".lean")


def lakefile_block(lib_of: dict[str, str], cfg: dict) -> str:
    skip = quarantined()
    rows = []
    for lib in libraries(cfg):
        mods = sorted(m for m in skip if lib_of.get(m) == lib)
        if mods:
            rows.append(f"  (`{lib}, #[" + ", ".join(f"`{m}" for m in mods) + "])")
    body = "#[]" if not rows else "#[\n" + ",\n".join(rows) + "]"
    return (f"{BLOCK_BEGIN}\n"
            "/-- Per library, the frozen theorem anchors in state `DRAFT_SORRY` and their provider modules.\n"
            "The frozen-anchor quarantine forbids every other module, the roots included, from importing\n"
            "them, so each library builds them as extra globs beside its root. -/\n"
            f"private def quarantinedModules : Array (Lean.Name × Array Lean.Name) := {body}\n"
            f"{BLOCK_END}")


def render_lakefile(lib_of: dict[str, str], cfg: dict) -> str:
    text = LAKEFILE.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"lakefile.lean has no generated block ({BLOCK_BEGIN!r} … {BLOCK_END!r})")
    return pattern.sub(lambda _m: lakefile_block(lib_of, cfg), text, count=1)


def lakefile_errors(cfg: dict) -> list[str]:
    """Each application has a non-default `lean_lib` whose only root is its root file, and the
    lakefile declares no library that the mapping does not know."""
    text = _helpers().code_mask(LAKEFILE.read_text(encoding="utf-8"))
    errors = []
    declared = re.findall(r"(?m)^lean_lib\s+«?([A-Za-z0-9_]+)»?", text)
    for lib in libraries(cfg):
        block = re.search(r"(?ms)^((?:@\[[^\]]*\]\s*)*)lean_lib\s+«?" + re.escape(lib) + r"»?\s+where\n(.*?)(?=^\S|\Z)", text)
        if not block:
            errors.append(f"lakefile.lean declares no lean_lib {lib}")
            continue
        if not re.search(r"roots\s*:=\s*#\[`" + re.escape(lib) + r"\]", block.group(2)):
            errors.append(f"lakefile.lean: lean_lib {lib} must have roots := #[`{lib}]")
        if "andSubmodules" in block.group(2) or "submodules" in block.group(2):
            errors.append(f"lakefile.lean: lean_lib {lib} must not glob submodules")
        if f"libGlobs `{lib}" not in block.group(2):
            errors.append(f"lakefile.lean: lean_lib {lib} must set globs := libGlobs `{lib}")
        default = "default_target" in block.group(1)
        if default != (lib == cfg["core"]["lib"]):
            errors.append(f"lakefile.lean: lean_lib {lib} must {'' if lib == cfg['core']['lib'] else 'not '}"
                          "be a default target")
    for lib in declared:
        if lib not in libraries(cfg):
            errors.append(f"lakefile.lean declares lean_lib {lib}, which scripts/build_roots.json does not know")
    return errors


def render(lib_of: dict[str, str], cfg: dict) -> dict[Path, str]:
    files: dict[Path, str] = {}
    skip = quarantined()
    core = cfg["core"]["lib"]
    titles = {a["lib"]: a.get("title", a["lib"]) for a in cfg["applications"]}
    for lib in libraries(cfg):
        base = cfg["core"]["parts"].split(".") if lib == core else [lib]
        # `lib_of` follows `all_modules`, i.e. the order of the source paths.
        names = [m for m, owner in lib_of.items() if owner == lib and m not in skip]
        ps = parts(base, names)
        for name, group in ps.items():
            area = ".".join(name.split(".")[len(base):])
            if area == "Top":
                what = f"the modules directly under `{LIB}`"
            elif area.endswith(".Top"):
                what = f"the modules directly under `{LIB}.{area[:-4]}`"
            else:
                what = f"the modules under `{LIB}.{area}`"
            if lib != core:
                what += f" that belong to `{lib}`"
            imports = "".join(f"public import {m}\n" for m in group)
            files[path_of(name)] = HEADER + "\n" + imports + PART_DOC.format(name=name, root=lib, area=what) + SECTION
        imports = "".join(f"public import {name}\n" for name in sorted(ps))
        doc = DOC if lib == core else app_doc(lib, titles[lib])
        files[ROOT / f"{lib}.lean"] = HEADER + ("\n" + imports if imports else "") + doc + SECTION
    files[LAKEFILE] = render_lakefile(lib_of, cfg)
    return files


def part_dirs(cfg: dict) -> list[Path]:
    return [ROOT / Path(*cfg["core"]["parts"].split("."))] + [ROOT / a["lib"] for a in cfg["applications"]]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check; do not write")
    parser.add_argument("--lib-of", nargs="+", metavar="X", help="print the library of each module or .lean path")
    parser.add_argument("--modules", metavar="LIB", help="print the modules of a library")
    parser.add_argument("--generated-paths", action="store_true", help="print the generated paths")
    args = parser.parse_args()
    cfg = load_config()
    if args.generated_paths:
        paths = [ROOT / f"{lib}.lean" for lib in libraries(cfg)] + part_dirs(cfg) + [LAKEFILE]
        print("\n".join(str(p.relative_to(ROOT)) for p in paths if p.exists()))
        return 0
    if args.lib_of:
        for x in args.lib_of:
            m = x[:-len(".lean")].replace("/", ".") if x.endswith(".lean") else x
            print(x, library_of(m, cfg))
        return 0
    lib_of, errors = classify(cfg)
    if args.modules:
        if args.modules not in libraries(cfg):
            print(f"unknown library {args.modules}; known: {', '.join(libraries(cfg))}", file=sys.stderr)
            return 2
        print("\n".join(m for m in sorted(lib_of) if lib_of[m] == args.modules))
        return 0
    errors += lakefile_errors(cfg)
    if errors:
        # The first words are matched by scripts/guard_mutation_suite.py.
        print("build roots: " + "\nbuild roots: ".join(errors), file=sys.stderr)
        return 1
    wanted = render(lib_of, cfg)
    stale = [p for d in part_dirs(cfg) if d.exists() for p in sorted(d.rglob("*.lean")) if p not in wanted]
    changed = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if changed or stale:
            # The first words are matched by scripts/guard_mutation_suite.py.
            print(f"{LIB}.lean is out of date; run scripts/gen_root_imports.py ("
                  + ", ".join(str(p.relative_to(ROOT)) for p in changed + stale) + ")",
                  file=sys.stderr)
            return 1
        return 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
    for p in stale:
        p.unlink()
    for d in part_dirs(cfg):
        for sub in sorted(d.rglob("*"), reverse=True) if d.exists() else []:
            if sub.is_dir() and not any(sub.iterdir()):
                sub.rmdir()
        if d.exists() and not any(d.iterdir()):
            d.rmdir()
    return 0


if __name__ == "__main__":
    sys.exit(main())
