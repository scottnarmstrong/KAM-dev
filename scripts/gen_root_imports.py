#!/usr/bin/env python3
"""Generate (or check) the root file `KAM.lean` and its parts `KAM/Root/*.lean`, which together
import every module of the library.

Usage:
  scripts/gen_root_imports.py          rewrite KAM.lean and KAM/Root/
  scripts/gen_root_imports.py --check  exit 1 if KAM.lean or a part is out of date

Every `.lean` file under `KAM/` is imported, except the frozen theorem anchors in state
`DRAFT_SORRY` and their provider modules: the frozen-anchor quarantine forbids any other module
from importing them. They are still compiled by a plain `lake build`, through the library glob
`.andSubmodules KAM` in the lakefile. No module may import the root file or a part.

The imports are split into parts so that no generated file exceeds the 1500-line limit: one part
`KAM.Root.<Area>` per top-level area `KAM.<Area>`, and an area with more than `LIMIT` modules is
split further by its next name component (`KAM.Root.<Area>.<Sub>`, with `Top` for the modules
directly under the area). `KAM.lean` imports the parts. The grouping follows the module names, so
adding a module changes only its own part.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = "KAM"
PARTS = "Root"
LIMIT = 1000

HEADER = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module
"""

DOC = """
/-!
# KAM

Root of the KAM formalization. This file imports the generated parts `KAM.Root.*`, which together
import every module of the library except the frozen theorem anchors that are still `DRAFT_SORRY`
and their provider modules, which the frozen-anchor quarantine forbids importing; a plain
`lake build` still compiles those through the library glob. It is generated by
`scripts/gen_root_imports.py`; do not edit it by hand, and never import it.
-/
"""

PART_DOC = """
/-!
# Root part `{name}`

Part of the generated root `KAM.lean`. It imports
{area},
except those that the root skips. Generated by `scripts/gen_root_imports.py`; do not edit it by
hand, and never import it.
-/
"""


def quarantined() -> set[str]:
    """Module names of DRAFT_SORRY theorem anchors and of their provider modules."""
    import json
    manifest = ROOT / "manifest" / "frozen-anchors.json"
    out: set[str] = set()
    for anchor in json.loads(manifest.read_text(encoding="utf-8")).get("anchors", []):
        if anchor.get("kind") == "theorem" and anchor.get("state") == "DRAFT_SORRY":
            out.add(".".join(Path(anchor["path"]).with_suffix("").parts))
            out.add(anchor["implementation"]["module"])
    return out


def modules() -> list[str]:
    skip = quarantined()
    names = []
    for path in sorted((ROOT / LIB).rglob("*.lean")):
        rel = path.relative_to(ROOT).with_suffix("")
        if len(rel.parts) > 1 and rel.parts[1] == PARTS:
            continue
        name = ".".join(rel.parts)
        if name not in skip:
            names.append(name)
    return names


def split(prefix: list[str], names: list[str]) -> dict[str, list[str]]:
    """Parts for the modules `names`, all of which start with `prefix` (a list of name components
    after `KAM`): one part if there are at most `LIMIT`, else one per next component."""
    if len(names) <= LIMIT:
        return {".".join([LIB, PARTS] + prefix): names}
    groups: dict[str, list[str]] = {}
    depth = len(prefix) + 1
    for n in names:
        comps = n.split(".")
        groups.setdefault(comps[depth] if len(comps) > depth + 1 else "Top", []).append(n)
    out: dict[str, list[str]] = {}
    for key, group in sorted(groups.items()):
        sub = split(prefix + [key], group) if key != "Top" else {
            ".".join([LIB, PARTS] + prefix + ["Top"]): group}
        out.update(sub)
    return out


def parts() -> dict[str, list[str]]:
    areas: dict[str, list[str]] = {}
    for n in modules():
        comps = n.split(".")
        areas.setdefault(comps[1] if len(comps) > 2 else "Top", []).append(n)
    out: dict[str, list[str]] = {}
    for area, names in sorted(areas.items()):
        out.update(split([area], names))
    return out


def path_of(module: str) -> Path:
    return ROOT / Path(*module.split(".")).with_suffix(".lean")


def render() -> dict[Path, str]:
    files: dict[Path, str] = {}
    ps = parts()
    for name, names in ps.items():
        area = ".".join(name.split(".")[2:])
        if area == "Top":
            what = f"the modules directly under `{LIB}`"
        elif area.endswith(".Top"):
            what = f"the modules directly under `{LIB}.{area[:-4]}`"
        else:
            what = f"the modules under `{LIB}.{area}`"
        imports = "".join(f"public import {m}\n" for m in names)
        files[path_of(name)] = HEADER + "\n" + imports + PART_DOC.format(name=name, area=what)
    imports = "".join(f"public import {name}\n" for name in sorted(ps))
    files[ROOT / f"{LIB}.lean"] = HEADER + ("\n" + imports if imports else "") + DOC
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check; do not write")
    args = parser.parse_args()
    wanted = render()
    stale = [p for p in sorted((ROOT / LIB / PARTS).rglob("*.lean")) if p not in wanted] \
        if (ROOT / LIB / PARTS).exists() else []
    changed = [p for p, text in wanted.items()
               if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if changed or stale:
            # The first words are matched by scripts/guard_mutation_suite.py.
            print(f"{LIB}.lean is out of date; run scripts/gen_root_imports.py ("
                  + ", ".join(str(p.relative_to(ROOT)) for p in changed + stale) + ")",
                  file=sys.stderr)
            return 1
        return 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
    for p in stale:
        p.unlink()
    for d in sorted((ROOT / LIB / PARTS).rglob("*"), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()
    return 0


if __name__ == "__main__":
    sys.exit(main())
