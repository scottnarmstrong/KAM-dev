#!/usr/bin/env python3
"""V2-PACKED-CONS-DATA (untrusted tooling; the Lean it writes is checked by the kernel): the cost of LG00's advice data
and of a packed form of it, measured on real advice parts (LG00 T′, `lg00-app` `applications/lg00/LG00/TP/Data/A*`).

Every advice definition of LG00 is `noncomputable def NAME : List ℤ := dzs [n₀, n₁, …]` (zigzag-coded naturals,
mostly 0): about 41 values per line, so a module of 124 KB holds about 40,000 numerals, and Lean elaborates each one.
The packed form keeps the definition (name, type, value) and stores the naturals as fixed-width fields of a few large
literals ("chunks", at most 88 decimal digits each, one per line):
    noncomputable def NAME : List ℤ := dzs (List.take LEN (unpkC W K [c₀, c₁, …]))
where `unpkC W K` reads `K` fields of `W` bits from each chunk, least significant first (`LG00X.Pack`; `W = 0` for a
list of zeros), or, when fewer chunks result, `dzs (List.take LEN (leb 0 0 (unpkC 8 36 [c₀, …])))`: the values' LEB128
bytes, 36 per chunk, or `dzs (List.take LEN (rle (leb 0 0 (unpkC 8 36 [c₀, …]))))`: the same over run-length tokens
(a run of zeros is one token; the advice is 95 % zeros). Written here, into DIR/src (a root outside every package):
  LG00X.Pack              `unpk`, `unpkC` (structural; the kernel evaluates them with its GMP `Nat` operations)
  LG00X.Floor             an empty data module with the advice's import (`LG00.Format`): the fixed cost per module
  LG00X.TP.Data.<A>       LG00's part <A>, verbatim, in namespace `LG00X.TP` (the original's cost)
  LG00X.TP.Data.<A>P      the same definitions packed, in namespace `LG00X.TP.P`
  LG00X.TP.Data.<A>Eq     `<A>P.NAME = <A>.NAME` for every definition, by `decide +kernel` (the packing is
                          faithful; its kernel cost is what a consumer of the values pays once)
  LG00X.TP.Data.MP        the packed definitions of all given parts in ONE module (fewer, larger modules)
  LG00X.TP.Data.Pk<i>     (--stats --emit=i,…) module i of the whole tree's plan: whole parts, packed, at most
                          MAX_LINES lines (the calibration of the projection)
Usage: python3 -I scripts/packed/cons_data_gen.py PART... [--stats [--emit=I,…]] [--dir=DIR]
       [--app=<lg00-app>/applications/lg00]       (PART e.g. A0 A100 A253)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DIR = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--dir=")),
           os.path.join(ROOT, ".lake", "v2-packed-data"))
APP = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--app=")),
           "/home/scott/KAM-dev-worktrees/lg00-app/applications/lg00")
PARTS = [a for a in sys.argv[1:] if not a.startswith("--")]
DEF = re.compile(r"noncomputable def (\S+) : List ℤ :=\s*dzs \[([0-9,\s]*)\]")
CHUNK_BITS = 290                                  # ≤ 88 decimal digits per chunk literal

HEAD = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

%s

/-!
%s
-/

@[expose] public noncomputable section
"""

PACK = HEAD % ("", """\
# Packed natural-number lists (V2-PACKED-CONS-DATA)

`unpk w k c`: the `k` fields of `w` bits of `c`, least significant first; `unpkC w k cs`: the
fields of the chunks `cs`, in order; `leb`: LEB128 decoding of a byte list; `rle`: run-length
decoding (a run of zeros is one token). Structural recursion;
the kernel evaluates `%`, `/`, `^`, `+`, `*` and `<` on literals with GMP.

Generated by `scripts/packed/cons_data_gen.py`.""") + """
namespace LG00X

/-- The `k` fields of `w` bits of `c`, least significant first. -/
def unpk (w : Nat) : Nat → Nat → List Nat
  | 0, _ => []
  | k + 1, c => c % 2 ^ w :: unpk w k (c / 2 ^ w)

/-- The fields of the chunks `cs` (`k` fields of `w` bits each), in order. -/
def unpkC (w k : Nat) : List Nat → List Nat
  | [] => []
  | c :: cs => unpk w k c ++ unpkC w k cs

/-- Run-length decoding: an even token `2v` is the value `v`; an odd token `2r + 1` is `r + 1`
zeros. -/
def rle : List Nat → List Nat
  | [] => []
  | t :: ts => if t % 2 = 0 then t / 2 :: rle ts else List.replicate (t / 2 + 1) 0 ++ rle ts

/-- LEB128 decoding of a byte list (the value so far `acc`, its next bit `sh`). -/
def leb (acc sh : Nat) : List Nat → List Nat
  | [] => []
  | b :: bs => if b < 128 then (acc + b * 2 ^ sh) :: leb 0 0 bs
    else leb (acc + (b - 128) * 2 ^ sh) (sh + 7) bs

end LG00X
"""

FLOOR = HEAD % ("public import LG00.Format", """\
# An empty data module (V2-PACKED-CONS-DATA): the fixed cost of one advice-shaped module

Generated by `scripts/packed/cons_data_gen.py`.""") + """
namespace LG00X.TP

open LG00

noncomputable def floorDef : List ℤ := dzs [0]

end LG00X.TP
"""


def defs(part):
    src = open(os.path.join(APP, "LG00", "TP", "Data", part + ".lean"), encoding="utf-8").read()
    out = [(m.group(1), [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()])
           for m in DEF.finditer(src)]
    n = len(re.findall(r"^noncomputable def ", src, re.M))
    if n != len(out):
        sys.exit("%s: %d definitions, %d of the advice form" % (part, n, len(out)))
    return src, out


def chunks(fields, w, k):
    """Pack `fields` (each < 2^w) into chunks of `k` fields, least significant first."""
    cs = []
    for i in range(0, max(len(fields), 1), k):
        c = 0
        for j, v in enumerate(fields[i:i + k]):
            c |= v << (w * j)
        cs.append(c)
    return cs


def leb_bytes(vals):
    out = []
    for v in vals:
        while v >= 128:
            out.append(128 + (v & 127))
            v >>= 7
        out.append(v)
    return out


def encode(vals):
    """The cheaper of the fixed-width form (`unpkC W K`) and the LEB128 form (`leb 0 0 (unpkC 8 36 …)`), by the
    number of chunks: (kind, w, k, chunks)."""
    w = max(v.bit_length() for v in vals) if vals else 0
    if w == 0:
        return ("fix", 0, len(vals), [0])
    k = max(1, CHUNK_BITS // w)
    fix = ("fix", w, k, chunks(vals, w, k))
    lb = ("leb", 8, CHUNK_BITS // 8, chunks(leb_bytes(vals), 8, CHUNK_BITS // 8))
    rl = ("rle", 8, CHUNK_BITS // 8, chunks(leb_bytes(rle_tokens(vals)), 8, CHUNK_BITS // 8))
    return min((fix, lb, rl), key=lambda e: len(e[3]))


def rle_tokens(vals):
    out, i = [], 0
    while i < len(vals):
        if vals[i]:
            out.append(2 * vals[i]); i += 1
        else:
            j = i
            while j < len(vals) and vals[j] == 0:
                j += 1
            out.append(2 * (j - i - 1) + 1); i = j
    return out


def packed(name, vals):
    kind, w, k, cs = encode(vals)
    body = ",\n".join("    %d" % c for c in cs)
    dec = "unpkC %d %d [\n%s]" % (w, k, body)
    if kind == "leb":
        dec = "leb 0 0 (%s)" % dec
    if kind == "rle":
        dec = "rle (leb 0 0 (%s))" % dec
    return "noncomputable def %s : List ℤ :=\n  dzs (List.take %d (%s))\n" % (name, len(vals), dec)


def check(vals, name):
    """The Python mirror of the decoders and `take`: the packing round-trips."""
    kind, w, k, cs = encode(vals)
    out = []
    for c in cs:
        for _ in range(k):
            out.append(c % (1 << w) if w else 0)
            c >>= w
    if kind in ("leb", "rle"):
        res, acc, sh = [], 0, 0
        for b in out:
            if b < 128:
                res.append(acc + (b << sh)); acc, sh = 0, 0
            else:
                acc += (b - 128) << sh; sh += 7
        out = res
    if kind == "rle":
        res = []
        for t in out:
            res.extend([t // 2] if t % 2 == 0 else [0] * (t // 2 + 1))
        out = res
    assert out[:len(vals)] == vals, name


def dzv(n):
    return n // 2 if n % 2 == 0 else -(n // 2) - 1


STATS = "--stats" in sys.argv
EMIT = [int(x) for a in sys.argv if a.startswith("--emit=") for x in a.split("=", 1)[1].split(",")]
MAX_LINES = 1400


def stats():
    """Every advice part of the tree, packed: lines, chunks and bytes, and the modules needed at <= MAX_LINES
    lines each (whole parts per module); against the originals' size and numerals."""
    d = os.path.join(APP, "LG00", "TP", "Data")
    parts = sorted((f[:-5] for f in os.listdir(d) if re.match(r"A\d+\.lean$", f)), key=lambda x: int(x[1:]))
    tot = dict(defs=0, vals=0, chunks=0, plines=0, pbytes=0, obytes=0)
    mods, cur, plan = 0, 0, [[]]
    for part in parts:
        src, ds = defs(part)
        pk = "\n".join(packed(nm, v) for nm, v in ds)
        pl = pk.count("\n") + 1
        tot["defs"] += len(ds)
        tot["vals"] += sum(len(v) for _, v in ds)
        tot["chunks"] += sum(len(encode(v)[3]) for _, v in ds)
        tot["plines"] += pl
        tot["pbytes"] += len(pk.encode())
        tot["obytes"] += len(src.encode())
        if cur + pl > MAX_LINES - 30 and cur:
            mods += 1
            cur = 0
            plan.append([])
        cur += pl
        plan[-1].append((part, pk))
    mods += 1 if cur else 0
    for i in EMIT:
        ps = plan[i]
        put("LG00X.TP.Data.Pk%d" % i, HEAD % ("public import LG00.Format\npublic import LG00X.Pack", """\
# LG00's advice, packed: module %d of the plan (parts %s; V2-PACKED-CONS-DATA)

The packed definitions of whole advice parts, at most %d lines per module.

Generated by `scripts/packed/cons_data_gen.py --stats --emit=%d`.""" % (i, ", ".join(p for p, _ in ps), MAX_LINES, i)) +
            "\nnamespace LG00X.TP.K\n\nopen LG00 LG00X\n\n" + "\n".join(pk for _, pk in ps) + "\nend LG00X.TP.K\n")
    print("parts %d, defs %d, values %d; original %.1f MB; packed %.1f MB, %d chunks, %d lines; "
          "modules at <= %d lines: %d" % (len(parts), tot["defs"], tot["vals"], tot["obytes"] / 1e6,
                                          tot["pbytes"] / 1e6, tot["chunks"], tot["plines"], MAX_LINES, mods))


def put(mod, txt):
    p = os.path.join(DIR, "src", *mod.split(".")) + ".lean"
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(txt)
    lines = txt.splitlines()
    print("%-26s %6d lines %8d bytes  lines>100: %d" % (mod, len(lines), len(txt.encode()),
                                                         sum(len(l) > 100 for l in lines)))


def main():
    put("LG00X.Pack", PACK)
    put("LG00X.Floor", FLOOR)
    allp = []
    for part in PARTS:
        src, ds = defs(part)
        for nm, v in ds:
            check(v, nm)
        orig = src.replace("namespace LG00.TP\n", "namespace LG00X.TP\n\nopen LG00\n")
        orig = orig.replace("end LG00.TP", "end LG00X.TP")
        orig = orig.replace("# LG00 advice windows", "# LG00's advice windows, verbatim (V2-PACKED-CONS-DATA)")
        put("LG00X.TP.Data.%s" % part, orig)
        pk = "\n".join(packed(nm, v) for nm, v in ds)
        allp.append((part, pk))
        put("LG00X.TP.Data.%sP" % part, HEAD % ("public import LG00.Format\npublic import LG00X.Pack", """\
# LG00's advice part %s, packed (V2-PACKED-CONS-DATA)

The definitions of `LG00.TP.Data.%s` (%d lists, %d values), each as fixed-width fields of chunk
literals, decoded by `unpkC`.

Generated by `scripts/packed/cons_data_gen.py`.""" % (part, part, len(ds), sum(len(v) for _, v in ds))) +
            "\nnamespace LG00X.TP.P\n\nopen LG00 LG00X\n\n" + pk + "\nend LG00X.TP.P\n")
        eqs = "\n".join("theorem eq_%d :\n    LG00X.TP.P.%s =\n      LG00X.TP.%s := by\n  decide +kernel\n"
                        % (i, nm, nm) for i, (nm, _) in enumerate(ds))
        put("LG00X.TP.Data.%sEq" % part, HEAD % (
            "public import LG00X.TP.Data.%s\npublic import LG00X.TP.Data.%sP" % (part, part), """\
# LG00's advice part %s: the packed form is the original (V2-PACKED-CONS-DATA)

Generated by `scripts/packed/cons_data_gen.py`.""" % part) + "\nnamespace LG00X.TP.Eq%s\n\n" % part + eqs +
            "\nend LG00X.TP.Eq%s\n" % part)
        # the consumer's cost: every value of every list forced in the kernel, original against packed
        for suf, ns, imp in (("Sum", "LG00X.TP", "LG00X.TP.Data.%s" % part),
                             ("PSum", "LG00X.TP.P", "LG00X.TP.Data.%sP" % part)):
            ths = "\n".join("theorem s_%d :\n    ((%s.%s).map Int.natAbs).sum =\n      %d := by\n  decide +kernel\n"
                            % (i, ns, nm, sum(abs(dzv(x)) for x in v)) for i, (nm, v) in enumerate(ds))
            put("LG00X.TP.Data.%s%s" % (part, suf), HEAD % ("public import " + imp, """\
# LG00's advice part %s: every value forced in the kernel (%s form; V2-PACKED-CONS-DATA)

What a consumer of the values pays: `(l.map Int.natAbs).sum` of every list, by `decide +kernel`.

Generated by `scripts/packed/cons_data_gen.py`.""" % (part, "packed" if suf == "PSum" else "original")) +
                "\nnamespace LG00X.TP.%s%s\n\n" % (part, suf) + ths + "\nend LG00X.TP.%s%s\n" % (part, suf))
    if STATS:
        stats()
    if len(PARTS) > 1:
        body = "\n".join(pk for _, pk in allp)
        put("LG00X.TP.Data.MP", HEAD % ("public import LG00.Format\npublic import LG00X.Pack", """\
# LG00's advice parts %s, packed into one module (V2-PACKED-CONS-DATA)

Generated by `scripts/packed/cons_data_gen.py`.""" % ", ".join(PARTS)) +
            "\nnamespace LG00X.TP.M\n\nopen LG00 LG00X\n\n" + body + "\nend LG00X.TP.M\n")


if __name__ == "__main__":
    main()
