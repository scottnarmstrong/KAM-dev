#!/usr/bin/env python3
"""V2-TOOLS-FIX: lay the generated forced-toy modules out into a cheap default-build subset and one opt-in kernel
test (untrusted tooling; it only moves generated text).

    python3 -I scripts/certifier/forced/forced_layout.py

Input: the full generated modules of forced_build.py, forced_routes.py and forced_mutations.py in
KAM/CertificateSharp/V2/Tests/Forced/ (`<T>Checks`, `<T>Base`, `<T>Claim`, `<T>RouteA/B/R`, `Tiny Mutations(Inv)`,
`TimeScale`, `MicroChecks`, `MicroBase`).  Output (orchestrator ruling: default modules of a few seconds each, anything
over ~10 s or ~2.5 GB opt-in):
  default build   Micro (the passing certificate: sharp, frozen A, frozen B): MicroChecksA/B, MicroGram,
                  MicroTorsion1/2/3 (independent stage proofs, built in parallel), MicroBase (assembly), MicroRoutes;
                  Tiny (the mutation target): TinyWitness (the witnesses, definitions only), TinyGram (the cheap Gram
                  and [4,0] stages), and the mutations in ten small modules TinyMut*;
  kernel-tests/CertificateSharp/V2/ForcedRoutes.lean   Tiny's remaining base proofs and routes A, L8', B, the frame-T
                  mutation, the whole TinyC2 chain and the time-normalization tori; it imports only library modules.
The full modules it reads are deleted afterwards (they are regenerated by the generators).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
D = os.path.join(ROOT, "KAM", "CertificateSharp", "V2", "Tests", "Forced")
KT = os.path.join(ROOT, "kernel-tests", "CertificateSharp", "V2", "ForcedRoutes.lean")
MOD = "KAM.CertificateSharp.V2.Tests.Forced."
HEADER = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

"""
NAME = re.compile(r"^(?:noncomputable )?(?:def|theorem) ([A-Za-z0-9_'.]+)", re.M)


def blocks(path):
    """the declarations of a generated module: {name: text} in order (helper defs of a mutation stay separate)."""
    text = open(path).read()
    m = re.search(r"\nopen [^\n]*\n", text)
    body = text[m.end():]
    body = body[:body.rindex("\nend KAM.")]
    out = []
    for blk in re.split(r"\n\s*\n", body):
        blk = blk.strip("\n")
        if not blk.strip() or blk.lstrip().startswith("/-!"):
            continue
        nm = NAME.search(blk)
        if nm is None:
            raise ValueError("no declaration in block of %s:\n%s" % (path, blk[:200]))
        out.append((nm.group(1), blk))
    return out


def pick(src, names):
    got = {n: b for n, b in src}
    missing = [n for n in names if n not in got]
    if missing:
        raise KeyError(missing)
    return [got[n] for n in names]


def wrap_doc(doc):
    out = []
    for line in doc.split("\n"):
        cur = ""
        for w in line.split(" "):
            if cur and len(cur) + 1 + len(w) > 100:
                out.append(cur)
                cur = w
            else:
                cur = (cur + " " + w) if cur else w
        out.append(cur)
    return "\n".join(out)


def module(imports, doc, ns, opens, decls):
    doc = wrap_doc(doc)
    txt = HEADER + "".join("public import %s\n" % i for i in imports) + "\n/-!\n%s\n-/\n\n" % doc
    txt += "@[expose] public section\n\nnamespace %s\n\nopen %s\n\n" % (ns, opens)
    txt += "\n\n".join(decls) + "\n\nend %s\n\nend\n" % ns
    for ln in txt.split("\n"):
        assert len(ln) <= 100, ln
    return txt


def section(ns, opens, decls):
    return "namespace %s\n\nopen %s\n\n" % (ns, opens) + "\n\n".join(decls) + "\n\nend %s\n" % ns


OPENS = "KAM KAM.Certificate KAM.CertificateSharp KAM.CertificateSharp.V2"
GRAM = ["G_eq", "dRows_eq", "gram_eq", "gram_ok", "eps_eq", "L_eq", "Gi_eq", "DL_eq", "N0_eq"]
TORS = [["ms_eq", "DG1_eq", "DG2_eq", "DGi0_eq", "DGi1_eq", "DN1_eq"], ["DN2_eq"], ["XN1_eq"]]
CLOSE = ["Tb_eq", "Y_eq", "torsion_ok", "base_ok"]
CHECKS = [["static_ok", "hamBounds_ok", "embedding_ok"], ["invariance_ok", "energy_ok"]]
MUTS = [
    ("MutClaims", "frame bounds and ray room: `bL`, `bN` below the measured rows, the claim `dx`, `nuRay`",
     ["mut_frameL", "mut_frameN", "mut_hamClaim", "mut_nuRay"]),
    ("MutCores", "ray room and schedules on the route cores: `disp = 1`, `θ = 1`, `10 X⋆`, route B `a = 1`",
     ["mut_dispRoom", "mut_theta", "mut_Xs", "mut_scheduleB", "mut_XsB"]),
    ("MutSites", "small-divisor separation: a box reaching the resonance fibers, a site bound halved",
     ["boxWide", "mut_boxFiber", "mut_siteBound"]),
    ("MutDenominator", "a Hamiltonian denominator whose ball contains `0`, and its separated control",
     ["mut_denominator", "ctl_denominator"]),
    ("MutSqrt", "a square-root operand reaching `Re ≤ 0`, and its separated control",
     ["mut_sqrtDomain", "ctl_sqrtDomain"]),
    ("MutCoef", "coefficients: a forcing amplitude and a Fourier coefficient of the torus",
     ["hamCoef", "mut_hamCoef", "uHalfMut", "mut_torusCoef"]),
    ("MutResidual", "a coefficient of the character witness; the residual claim `err`",
     ["E1TermsMut", "mut_witnessCoef", "mut_err"]),
    ("MutAdvice", "the energy level `E0`; a missing advice key of each stage",
     ["mut_E0", "mut_adviceFull", "mut_adviceLow"]),
    ("MutConvA", "conventions: the angle degree of `u`, the ray scalar `s`",
     ["mut_angleDeg", "mut_rayScalar"]),
    ("MutConvB", "conventions: the time scale of `H`, the order of the actions",
     ["mut_timeScale", "mut_swapActions"]),
]


def main():
    src = {}
    for nm in ("TinyChecks", "TinyBase", "TinyClaim", "TinyRouteA", "TinyRouteB", "TinyRouteR", "TinyMutations",
               "TinyMutationsInv", "TinyC2Checks", "TinyC2Base", "TinyC2Claim", "TinyC2RouteA", "TimeScale",
               "MicroChecks", "MicroBase"):
        src[nm] = blocks(os.path.join(D, nm + ".lean"))
    out = {}
    # ---- Micro: the passing certificate of the default build
    mb = src["MicroChecks"] + src["MicroBase"]
    for i, names in enumerate(CHECKS):
        out["MicroChecks%s" % "AB"[i]] = module(
            [MOD + "MicroData", "KAM.CertificateSharp.V2.Engine"],
            "# Landed sub-checks of the forced toy `Micro` (part %s)\n\n`%s`, one `decide +kernel` each." % (
                "AB"[i], "`, `".join(names)), "KAM.CertificateSharp.V2.Forced.Micro", OPENS, pick(mb, names))
    gram_doc = ("# The Gram check and the stages `L`, `G⁻¹`, `DL`, `[4, 0]` of the forced toy `%s`\n\n"
                "Each stage literal of `%sStages` (computed by the Python mirror) is re-proved by its own\n"
                "kernel run and rewritten into the landed `gramCheck` (`gramCheck_eq_of_rows`).")
    for T in ("Micro", "Tiny"):
        b = src["MicroBase"] if T == "Micro" else src["TinyBase"]
        out["%sGram" % T] = module([MOD + T + "Stages", "KAM.CertificateSharp.Kernel.Stage",
                                    "KAM.CertificateSharp.V2.Engine"], gram_doc % (T, T),
                                   "KAM.CertificateSharp.V2.Forced.%s" % T, OPENS, pick(b, GRAM))
    for i, names in enumerate(TORS):
        out["MicroTorsion%d" % (i + 1)] = module(
            [MOD + "MicroStages", "KAM.CertificateSharp.Kernel.Stage", "KAM.CertificateSharp.V2.Engine"],
            "# Torsion stages of the forced toy `Micro` (part %d)\n\n`%s`: stage literals re-proved by their own "
            "kernel runs\n(`eq_of_matBeq`, `eq_of_optModelsBeq`)." % (i + 1, "`, `".join(names)),
            "KAM.CertificateSharp.V2.Forced.Micro", OPENS, pick(src["MicroBase"], names))
    out["MicroBase"] = module(
        [MOD + "MicroGram", MOD + "MicroTorsion1", MOD + "MicroTorsion2", MOD + "MicroTorsion3",
         MOD + "MicroChecksA", MOD + "MicroChecksB"],
        "# Every landed sub-check of the forced toy `Micro`\n\n`torsion_ok` assembles the torsion stages of "
        "`MicroTorsion1/2/3` and `MicroGram` (`torsionModels_eq_of_stages`);\n`base_ok` is "
        "`landedBase.check Micro.cert = true`.", "KAM.CertificateSharp.V2.Forced.Micro", OPENS,
        pick(src["MicroBase"], CLOSE))
    # ---- Tiny: the witnesses (definitions only) and the mutations
    wit = (pick(src["TinyClaim"], ["Rclaim"]) + pick(src["TinyRouteA"], ["refinedWit"]) +
           pick(src["TinyRouteB"], ["refinedBWit"]) + pick(src["TinyRouteR"], ["refinedWitR"]))
    out["TinyWitness"] = module(
        [MOD + "TinyData", "KAM.CertificateSharp.V2.RouteAll"],
        "# The witnesses of the forced toy `Tiny` (definitions only)\n\nThe refined claim `Rclaim`, the "
        "route-A witness `refinedWit`, the route-B witness `refinedBWit` and the L8′\nwitness `refinedWitR`, "
        "as forced_witness.py chose them. The mutation modules `TinyMut*` change one input\nof them; the passing "
        "checks are in the opt-in `kernel-tests/CertificateSharp/V2/ForcedRoutes.lean`.",
        "KAM.CertificateSharp.V2.Forced.Tiny", OPENS, wit)
    muts = src["TinyMutations"] + src["TinyMutationsInv"]
    for nm, doc, names in MUTS:
        out["Tiny" + nm] = module(
            [MOD + "TinyWitness", MOD + "TinyGram"],
            "# Mutations of the forced toy `Tiny` that must be rejected: %s\n\nEach theorem changes one input of "
            "the passing certificate or witness and decides the single\ncheck that must reject it "
            "(`scripts/certifier/forced/forced_mutations.py`, the mirror verdicts in\n"
            "`scripts/certifier/fixtures/forced-toy/Tiny_mutations.json`)." % doc,
            "KAM.CertificateSharp.V2.Forced.Tiny", OPENS, pick(muts, names))
    # ---- the opt-in kernel test
    tb = src["TinyChecks"] + src["TinyBase"]
    tiny = (pick(tb, CHECKS[0] + CHECKS[1] + TORS[0] + TORS[1] + TORS[2] + CLOSE) +
            [b for n, b in src["TinyClaim"] if n != "Rclaim"] +
            [b for n, b in src["TinyRouteA"] if n != "refinedWit"] +
            [b for n, b in src["TinyRouteB"] if n != "refinedBWit"] +
            [b for n, b in src["TinyRouteR"] if n != "refinedWitR"] + pick(muts, ["mut_frameT"]))
    c2 = ([b for n, b in src["TinyC2Checks"]] + [b for n, b in src["TinyC2Base"]] +
          [b for n, b in src["TinyC2Claim"]] + [b for n, b in src["TinyC2RouteA"]])
    ts = [b for n, b in src["TimeScale"]]
    kt = HEADER + "".join("public import %s\n" % i for i in [
        MOD + "TinyGram", MOD + "TinyWitness", MOD + "TinyFreq", MOD + "TinyC2Stages", MOD + "TinyC2Freq",
        MOD + "Lemmas", "KAM.CertificateSharp.Kernel.Stage", "KAM.CertificateSharp.V2.RouteAll",
        "KAM.SpinOrbit.Rotated"])
    kt += """
/-!
# The forced toys' route checks and the time normalization (opt-in, not part of the library)

Not built by anything (`kernel-tests/README.md`); the file stands for
`KAM.CertificateSharp.V2.Tests.ForcedRoutes`. It imports only library modules (the data, witnesses
and cheap Gram stages of `KAM/CertificateSharp/V2/Tests/Forced/`), so it runs directly:
`nice -n 10 lake env lean kernel-tests/CertificateSharp/V2/ForcedRoutes.lean`.

* `Tiny`: the remaining landed sub-checks and torsion stages (`base_ok`), the refined claim
  (`hamClaim_ok`, `frame_ok`), route A (`refinedA_passes`, `refinedA_torus`), L8′
  (`refinedR_passes`), route B (`refinedB_passes`, `refinedB_torus`), and the mutation `mut_frameT`
  (it needs every torsion stage);
* `TinyC2`: the time normalization of `Tiny` (H and ω* doubled) through route A;
* `timeScale_*`: the two normalizations related by `invarianceError_const_mul`, both tori certified.

The cheap subset stays in the default build: the passing certificate `Micro` (sharp, frozen A,
frozen B: `MicroRoutes`) and the mutations of `Tiny` (`TinyMut*`).
-/

@[expose] public section

"""
    kt += section("KAM.CertificateSharp.V2.Forced.Tiny", OPENS, tiny) + "\n"
    kt += section("KAM.CertificateSharp.V2.Forced.TinyC2", OPENS, c2) + "\n"
    kt += section("KAM.CertificateSharp.V2.Forced", "KAM KAM.Certificate KAM.SpinOrbit", ts) + "\nend\n"
    for ln in kt.split("\n"):
        assert len(ln) <= 100, ln
    assert len(kt.split("\n")) <= 1500, len(kt.split("\n"))
    # ---- write, then remove the full modules
    for nm, txt in out.items():
        with open(os.path.join(D, nm + ".lean"), "w") as fh:
            fh.write(txt)
    os.makedirs(os.path.dirname(KT), exist_ok=True)
    with open(KT, "w") as fh:
        fh.write(kt)
    for nm in ("TinyChecks", "TinyBase", "TinyClaim", "TinyRouteA", "TinyRouteB", "TinyRouteR", "TinyMutations",
               "TinyMutationsInv", "TinyC2Checks", "TinyC2Base", "TinyC2Claim", "TinyC2RouteA", "TimeScale",
               "MicroChecks"):
        os.remove(os.path.join(D, nm + ".lean"))
    import json
    jp = os.path.join(ROOT, "scripts", "certifier", "fixtures", "forced-toy", "Tiny_mutations.json")
    home = {n: "Tiny" + g for g, _, names in MUTS for n in names}
    home["mut_frameT"] = "kernel-tests/CertificateSharp/V2/ForcedRoutes.lean"
    rows = json.load(open(jp))
    for r in rows:
        r["module"] = home.get(r["name"])
    with open(jp, "w") as fh:
        json.dump(rows, fh, indent=1, default=str)
    print("default modules:", sorted(out), "\nkernel test:", os.path.relpath(KT, ROOT), len(kt.split("\n")), "lines")


if __name__ == "__main__":
    sys.exit(main())
