#!/usr/bin/env python3
"""LOCK-DATA, SOS option (a): the two new cfgLow advice entries as lock-owned data modules (untrusted tooling).

    python3 lock_sosk_lean.py SRC_D_DIR OUTDIR

SRC_D_DIR: a full `lock_lean.py` emission from gen_D100d (the book with [7, 1] and [7, 2] appended as entries
1082, 1083). The live base data (lean/src) is not re-emitted: this extracts exactly the definition blocks of
`advLow.p1082.*` and `advLow.p1083.*` (source order, verbatim) into AdvLowSOS{j}.lean (chained, <= 1400 lines) and
writes AdvLowSOS.lean with the seventh chunk `advLow.b6 : AdviceBook` (the two book lines, verbatim). Cert.lean's
cfgLow then uses `advLow ++ advLow.b6`: every existing entry keeps its index.
"""
import os
import re
import sys

HDR = """/-
Copyright (c) 2026 Scott Armstrong, Zohar Komargodski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Scott Armstrong, Zohar Komargodski
-/
module

{imports}

/-!
# {title} (generated)

{doc}
Generated by `scripts/spin_orbit/lock_sosk_lean.py`. Do not edit.
-/

@[expose] public section

namespace KAM.SpinOrbit.Data.LockN65

open KAM.Certificate

{body}
end KAM.SpinOrbit.Data.LockN65
"""
NS = "KAM.SpinOrbit.Data.LockN65"


def blocks(text):
    body = text.split("open KAM.Certificate\n", 1)[1].rsplit("end KAM.SpinOrbit.Data.LockN65", 1)[0]
    out, cur = [], None
    for l in body.split("\n"):
        if l.startswith("def "):
            if cur:
                out.append(cur)
            cur = [l]
        elif cur is not None:
            cur.append(l)
    if cur:
        out.append(cur)
    return out


def main(src, odir):
    d = os.path.join(src, "KAM", "SpinOrbit", "Data", "LockN65")
    files = sorted((f for f in os.listdir(d) if re.match(r"^AdvLow\d+\.lean$", f)), key=lambda f: int(f[6:-5]))
    keep = []
    for f in files:
        for b in blocks(open(os.path.join(d, f)).read()):
            if re.match(r"^def advLow\.p108[23]\.", b[0]):
                while b and b[-1].strip() == "":
                    b = b[:-1]
                keep.append(b + [""])
    names = [re.match(r"^def (\S+)", b[0]).group(1) for b in keep]
    for p in ("1082", "1083"):
        for part in ("rr", "ii", "ri", "ir"):
            assert "advLow.p%s.%s" % (p, part) in names, (p, part)
    parts, cur, n = [], [], 0
    for b in keep:
        if cur and n + len(b) > 1400:
            parts.append(cur)
            cur, n = [], 0
        cur.append(b)
        n += len(b)
    if cur:
        parts.append(cur)
    base = ["%s.Format" % NS, "%s.ZCode" % NS]
    os.makedirs(odir, exist_ok=True)
    mods = []
    for j, p in enumerate(parts):
        imps = base + mods[-1:]
        text = HDR.format(imports="\n".join("public import " + i for i in imps),
                          title="The SOS-square advice of `advLow`, part %d" % j,
                          doc="Packed-product advice of the SOS squares `[7, 1]`, `[7, 2]` (compact `zdecs` literals).",
                          body="\n".join(l for b in p for l in b))
        assert max(len(l) for l in text.split("\n")) <= 100 and text.count("\n") <= 1500
        open(os.path.join(odir, "AdvLowSOS%d.lean" % j), "w").write(text)
        mods.append("%s.AdvLowSOS%d" % (NS, j))
    book = [l for l in open(os.path.join(d, "AdvLow.lean")).read().split("\n")
            if re.match(r"^\s*\(\[7, [12]\], \.packed 112 advLow\.p108[23]\.", l)]
    assert len(book) == 2, book
    body = ["/-- The seventh chunk of the cfgLow book: the packed advice of the two SOS squares. -/",
            "def advLow.b6 : AdviceBook := [", book[0].rstrip().rstrip(",") + ",", book[1].rstrip().rstrip(",").rstrip("]") + "]", ""]
    text = HDR.format(imports="\n".join("public import " + i for i in base + mods[-1:]),
                      title="The SOS-square chunk of `advLow`",
                      doc="`advLow.b6`: the entries `[7, 1]` (pLo) and `[7, 2]` (pHi), appended after the book.",
                      body="\n".join(body))
    open(os.path.join(odir, "AdvLowSOS.lean"), "w").write(text)
    print("blocks", len(keep), "parts", len(parts), "lines", sum(len(b) for b in keep))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
