#!/usr/bin/env python3
"""LOCK-DATA: emit the N = 65 lock certificate as Lean data modules under KAM/SpinOrbit/Data/LockN65/ (untrusted
tooling; the kernel checks whatever is emitted).  Adapted from SO-DATA3's sofx_lean.py, whose helpers (Tree,
emit_blob, emit_advice, rat_lit, row_lines, num) are reused unchanged; only the lock's certificate shape differs:
backend `LockBackend = CertFixed 112`, the Hamiltonian `.mul (.const c) (lockHamExpr (8/65) lunarLockCentre)`,
four exp, eight inv, two character and four sqrt witnesses, the box `lockN65Box`, and the kp = 4 witness.

    SO_LOCK_DATA=... SO_LOCK_SIZE=... python3 lock_lean.py GENDIR [ROOT]
"""
import os
import pickle
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.set_int_max_str_digits(0)
import sofx_lean as SL       # noqa: E402
import lock_seg as LSG       # noqa: E402
import lock_gen as LG        # noqa: E402
import lock_bites as LB      # noqa: E402

TORUS = "LockN65"
SL.FORMAT = "KAM.SpinOrbit.Data.LockN65.Format"
TY = "LockBackend"
GEN = "Generated by `scripts/spin_orbit/lock_lean.py`. Do not edit."


def poly_mod(tree, name, terms, title):
    return SL.emit_blob(tree, name, "List (CertKey × CC %s)" % TY, [SL.term_row(t) for t in terms], title)


def rl(q):
    return SL.rat_lit(q)


def main(gdir, root):
    c, d = LSG.lock_cert(gdir)
    g = pickle.load(open(os.path.join(gdir, "gen.pkl"), "rb"))
    tree = SL.Tree(root, TORUS)
    imps = []
    e = c.emb
    polys = {}
    for k, L in (("angle", e.angle), ("action", e.action)):
        for i, x in enumerate(L):
            nm = "%s%d" % (k, i)
            if x.half:
                imps.append(poly_mod(tree, nm, x.half, "Embedding `%s` half terms" % nm))
                polys[nm] = (x.zero, nm)
            else:
                polys[nm] = (x.zero, None)
    # witness polynomials, each distinct one emitted once
    seen = {}

    def wpoly(P, stem):
        key = tuple(P)
        if key not in seen:
            nm = "%s%d" % (stem, len([1 for v in seen.values() if v.startswith(stem)]))
            if len(P) > 4:
                imps.append(poly_mod(tree, nm, P, "Witness polynomial `%s`" % nm))
                seen[key] = nm
            else:
                seen[key] = "[" + ", ".join("tm %s %s %s %s" % (SL.num(k[0]), SL.num(k[1]), SL.num(z[0]),
                                                                SL.num(z[1])) for k, z in P) + "]"
        return seen[key]

    w = c.wit
    expW = [(wpoly(P, "expW"), ph, po) for P, ph, po in w.expWit]
    invW = [wpoly(P, "invW") for P in w.invWit]
    chW = [(k, wpoly(P, "charW"), ph, po) for k, (P, ph, po) in w.charWit]
    sqW = [(s, wpoly(P, "sqrtW"), a, m) for s, (P, a, m) in w.sqrtWit]
    gn = {}
    for i in range(2):
        for j in range(2):
            gn[(i, j)] = wpoly(c.gramInv[i][j], "gram")
    gr = g["graph"]
    sos = {nm: (wpoly(gr[nm], nm) if gr[nm] else "[]") for nm in ("sosMono", "sosLo", "sosHi")}
    imps.append(SL.emit_advice(tree, "advFull", g["books"]["cfgFull"]))
    imps.append(SL.emit_advice(tree, "advLow", g["books"]["cfgLow"]))
    body = []

    def rp(nm):
        z, h = polys[nm]
        return "⟨%sZero, %s⟩" % (nm, h if h else "[]")

    for nm in ("angle0", "angle1", "action0", "action1"):
        body.extend(SL.row_lines(["def %sZero : %s :=" % (nm, TY), "⟨%s⟩" % SL.num(polys[nm][0])], ""))
    body += ["", "/-- The embedding. -/", "def emb : CertEmbedding %s where" % TY,
             "  angleDeg := [%s]" % ", ".join(str(x) for x in e.angleDeg)]
    body += SL.row_lines(["angle := [" + rp("angle0") + ",", rp("angle1") + "]"], "  ")
    body += ["  actionDeg := [%s]" % ", ".join(str(x) for x in e.actionDeg)]
    body += SL.row_lines(["action := [" + rp("action0") + ",", rp("action1") + "]"], "  ")

    def lst(items):
        return ["[" + it + ("," if i + 1 < len(items) else "]") if i == 0 else " " + it +
                ("," if i + 1 < len(items) else "]") for i, it in enumerate(items)] or ["[]"]

    body += ["", "/-- The witnesses: exp and inv in slot order, characters under their normalized keys, sqrt",
             "keyed by slot. -/", "def wit : Witnesses %s where" % TY, "  expWit :="]
    body += ["    " + l for l in lst(["⟨⟨%s⟩, %d, %d⟩" % (p, ph, po) for p, ph, po in expW])]
    body += ["  invWit :="] + ["    " + l for l in lst(["⟨%s⟩" % p for p in invW])]
    body += ["  charWit :="] + ["    " + l for l in lst(["([%s], ⟨⟨%s⟩, %d, %d⟩)" % (
        ", ".join(str(x) for x in k), p, ph, po) for k, p, ph, po in chW])]
    body += ["  sqrtWit :="] + ["    " + l for l in lst(["(%d, ⟨⟨%s⟩, %s, %s⟩)" % (
        s, p, SL.q_lit(a), SL.q_lit(m)) for s, p, a, m in sqW])]
    body += ["", "/-- The Gram witness. -/", "def gramInv : List (List (CertPoly %s)) :=" % TY,
             "  [[⟨%s⟩, ⟨%s⟩], [⟨%s⟩, ⟨%s⟩]]" % (gn[(0, 0)], gn[(0, 1)], gn[(1, 0)], gn[(1, 1)])]
    body += ["", "/-- The torsion witness. -/", "def torsInv : List (List (CC %s)) := [" % TY]
    S = c.torsInv
    for i, r in enumerate(S):
        for j, z in enumerate(r):
            end = "," if j + 1 < len(r) else ("]," if i + 1 < len(S) else "]]")
            body += SL.row_lines([("[" if j == 0 else " ") + SL.cc(z) + end], "  ")
    pe = c.piEnc
    body += ["", "/-- The `π` enclosure. -/", "def piEnc : PiEnclosure %s where" % TY]
    body += SL.row_lines(["centre := ⟨%s⟩" % SL.num(pe.centre)], "  ")
    body += ["  rad := ⟨%s⟩" % SL.num(pe.rad), "  machinK := %d" % pe.machinK, "  machinJ := %d" % pe.machinJ]
    for nm in ("sosMono", "sosLo", "sosHi"):
        body += ["", "def %sPoly : CertPoly %s := ⟨%s⟩" % (nm, TY, sos[nm])]
    tree.write("Pieces", imps + [SL.FORMAT], "The N = 65 lock: data pieces (generated)",
               "Embedding, witnesses, `π` enclosure and the two advice books.\n" + GEN, body)
    emit_cert(tree, c, g)
    emit_witness(tree, c, g)
    for rel, text in sorted(tree.files.items()):
        os.makedirs(os.path.dirname(tree.path(rel)), exist_ok=True)
        with open(tree.path(rel), "w") as f:
            f.write(text)
    nbytes = sum(len(t.encode()) for t in tree.files.values())
    print(len(tree.files), "files", sum(t.count("\n") for t in tree.files.values()), "lines", nbytes, "bytes")
    return nbytes


def emit_cert(tree, c, g):
    p = c.params
    lo, hi = c.sqrt5
    body = ["/-- The enclosure `√5 ∈ [rootLo, rootHi]`. -/", "def rootLo : ℚ :="]
    body += ["  " + l for l in rl(lo)] + ["", "def rootHi : ℚ :="] + ["  " + l for l in rl(hi)]
    body += ["", "/-- The `ℚ(√5)` coefficients of `lunarRotFreq (lunarNuPlusN 65) 1` (`lunarRotFreqPlusN_eq`). -/",
             "def freqCoeffs : List (List ℚ) :="]
    co = c.freqCoeffs
    body += ["  [[%s, %s], [%s]]" % (SL.q_lit(co[0][0]), SL.q_lit(co[0][1]), SL.q_lit(co[1][0]))]
    body += ["", "/-- The frequency box (the interval evaluation of `freqCoeffs`). -/", "def freqBox : FreqBox := ["]
    for i, (a, r) in enumerate(c.freqBox):
        body += ["  ("] + ["    " + l for l in rl(a)] + ["  ,"] + ["    " + l for l in rl(r)]
        body += ["  )" + ("," if i + 1 < len(c.freqBox) else "]")]

    def wt(W):
        return ["⟨" + rl(W.rho)[0] + ","] + ["  " + l for l in rl(W.w)] + ["⟩"]

    body += ["", "def weight : CertWeight :="] + ["  " + l for l in wt(c.weight)]
    body += ["", "def weightH : CertWeight :="] + ["  " + l for l in wt(c.weightH)]
    for nm, cfg, adv in (("cfgFull", c.cfgFull, "advFull"), ("cfgLow", c.cfgLow, "advLow")):
        body += ["", "def %s : ModelConfig %s :=" % (nm, TY),
                 "  ⟨%d, %d, %d, CertFixed.toMant lockPrecision, %s⟩" % (cfg.cutoff, cfg.taylorN, cfg.halvings,
                                                                          adv)]
    names = dict(tau="tau", rho="rho", rhoInf="rhoInf", M="M", sK="σK", sB="σB", sT="σT", mu="μ", gbar="γbar",
                 som="σω", nu="nuRay", gamma="γ", s="s", err="err", E0="E0", disp="disp")
    body += ["", "/-- The parameters (LOCK-DATA sizing: exact mirrors; `lock_gen.py`). -/",
             "def params : CertParams where"]
    for k, ln in names.items():
        body += ["  %s := %s" % (ln, rl(p[k])[0] if k != "tau" else str(int(p[k])))]
    body += ["", "/-- The Hamiltonian's time scale `c = κ s` (`κ = 1`). -/",
             "def hamScale : ℚ := %s" % SL.q_lit(c.hamScale)]
    body += ["", "/-- The torus certificate. -/", "def base : TorusCertificate 2 %s where" % TY,
             "  params := params", "  ham := .mul (.const hamScale) (lockHamExpr (8 / 65) lunarLockCentre)",
             "  weightH := weightH",
             "  centre := [%s]" % ", ".join(rl(x)[0] for x in c.centre),
             "  radius := [%s]" % ", ".join(rl(x)[0] for x in c.radius),
             "  freqBox := freqBox", "  emb := emb", "  weight := weight", "  wit := wit",
             "  gramInv := gramInv", "  torsInv := torsInv", "  cfgFull := cfgFull", "  cfgLow := cfgLow",
             "  piEnc := piEnc", "  expHalvings := %d" % c.expHalvings, "  expOrder := %d" % c.expOrder]
    gr = g["graph"]
    body += ["", "/-- The graph certificate. -/", "def graph : SoGraphCert %s where" % TY, "  base := base"]
    for k in ("mono", "mono0", "pLo", "pLo0", "pHi", "pHi0"):
        body += ["  %s := %s" % (k.replace("0", "₀"), rl(gr[k])[0])]
    body += ["  sosMono := sosMonoPoly", "  sosLo := sosLoPoly", "  sosHi := sosHiPoly"]
    body += ["", "/-- The lock certificate. -/", "def cert : LockGraphCert %s where" % TY, "  graph := graph",
             "  Ω := 8 / 65", "  cs := lunarLockCentre", "  κ := hamScale"]
    tree.write("Cert", [tree.module("Pieces"), "KAM.SpinOrbit.Lock.Graph"],
               "The N = 65 lock: the certificate (generated)",
               "Parameters, Hamiltonian, frequency box, weights, model configurations and graph data.\n" + GEN,
               body, opens="KAM.Certificate KAM.SpinOrbit KAM.SpinOrbit.Lock")


def emit_witness(tree, c, g):
    v2 = g["v2"]
    w = {k: v for k, v in v2["w"].items()}
    R = g["claims"]
    body = ["/-- The refined claim: the Ham sums and frame majorants, rounded up (exact mirrors of",
            "`checkHamClaim` and `checkFrameMajorants`). -/", "def refClaim : RefClaim where"]
    body += ["  %s := %s" % (k, SL.q_lit(R[k])) for k in ("dh", "dx", "d2x", "d2h", "bL", "bN", "bNt", "bT")]
    body += ["", "/-- The routeARefined witness (kp = 4; certified bites at `δ₀, δ₁, b₀, …, b₃`). -/",
             "def refinedWit : RefinedWit where", "  core :="]
    lstq = lambda s: "[" + ", ".join(SL.q_lit(x) for x in eval_list(s)) + "]"
    core = [("Xs", SL.q_lit(v2["Xs"])), ("kp", str(LB.KP)), ("th", "1 / 8"), ("c", lstq(w["c"])),
            ("cbar", lstq(w["cbar"]))]
    core += [(k, SL.q_lit(w[k])) for k in ("ctail", "sB", "sT", "sLt", "sN", "sNt", "t")] + [("J", str(LB.J))]
    for i, (k, val) in enumerate(core):
        body += SL.row_lines([("{ " if i == 0 else "  ") + "%s := %s" % (k, val) +
                              (" }" if i + 1 == len(core) else "")], "    ")
    body += ["  R := refClaim", "  κ := 1", "  sites :="]

    def site(t):
        b = LB.BITES.get(t)
        return "none" if b is None else "some ⟨%s, %d, 8, %s⟩" % (SL.q_lit(b[1]), b[0], SL.q_lit(b[2]))

    sts = [(site(("d", s)), site(("b", s))) for s in range(LB.KP)]
    for i, (a, b) in enumerate(sts):
        body += SL.row_lines([("[" if i == 0 else " ") + "(%s," % a, "%s)" % b + ("," if i + 1 < len(sts) else "]")],
                             "    ")
    tree.write("Witness", ["KAM.CertificateSharp.V2.RouteARefined"],
               "The N = 65 lock: the v2 refined-route witness (generated)",
               "The witness `Sum.inr (Sum.inr refinedWit)` of `checkTorusCertificateV2 routeAV2`.\n" + GEN, body,
               opens="KAM.Certificate KAM.CertificateSharp.V2")


def eval_list(s):
    """the witness lists were stored as str(list of Fractions)."""
    if isinstance(s, (list, tuple)):
        return [F(x) for x in s]
    return [eval(x, {"Fraction": F}) for x in [s]][0]


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", ".."))
