# ---------------------------------------------------------------------------------------------- formatting
def wrap(parts, indent="  "):
    """`sofx_lean.row_lines`, never splitting `decide +kernel`."""
    toks = []
    for p in parts:
        if toks and toks[-1].endswith("decide") and p.startswith("+kernel"):
            toks[-1] += " " + p
        else:
            toks.append(p)
    return SL.row_lines(toks, indent)


def tm(t):
    (k0, k1), (re, im) = t
    return "tm %s %s %s %s" % (num(k0), num(k1), num(re), num(im))


SKELETON = False     # --skeleton: every literal cut to one term (typecheck harness only; types unchanged)


def terms_defs(name, terms, named=False):
    """chunk defs `name.cK` of <= ROWS rows; returns (defs lines, the term-list expression); `named`: always define
    `name` itself (a memo's output list is referenced by name)."""
    if SKELETON:
        terms = terms[:1]
    if not terms:
        if named:
            return ["def %s : List (CertKey × CC %s) := []" % (name, TY), ""], name
        return [], "[]"
    chunks = [terms[i:i + ROWS] for i in range(0, len(terms), ROWS)]
    out = []
    for k, ch in enumerate(chunks):
        out.append("def %s.c%d : List (CertKey × CC %s) := [" % (name, k, TY))
        for i, t in enumerate(ch):
            out.append("  " + tm(t) + ("," if i + 1 < len(ch) else "]"))
        out.append("")
    if len(chunks) == 1 and not named:
        return out, "%s.c0" % name
    nm = ["%s.c%d" % (name, k) for k in range(len(chunks))]
    out += wrap(["def %s : List (CertKey × CC %s) := List.flatten [" % (name, TY)] +
                [x + "," for x in nm[:-1]] + [nm[-1] + "]"], "") + [""]
    return out, name


def model_defs(name, m, norm=None, doc=None):
    lines, expr = terms_defs(name + "T", list(m.poly))
    lines += ([] if doc is None else ["/-- %s -/" % doc])
    lines += wrap(["def %s : CertModel %s :=" % (name, TY), "⟨%d, ⟨%s⟩, ⟨%s⟩⟩" % (m.deg, expr, num(m.rad))], "")
    if norm is not None:
        lines += ["def %sN : %s := ⟨%s⟩" % (name, TY, num(norm))]
    return lines + [""]


def fixed(v):
    return "(⟨%s⟩ : %s)" % (num(v), TY)


def nat_list(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def autowrap(lines):
    """split any line over COLS columns at spaces; continuation lines indented 4 more (Lean needs only a deeper
    indentation for a continued term); `decide +kernel` is never split."""
    out = []
    for l in lines:
        for x in l.replace("decide +kernel", "decide\u00a0+kernel").split("\n"):
            if len(x.replace("\u00a0", " ")) <= COLS:
                out.append(x)
                continue
            ind = len(x) - len(x.lstrip())
            toks = x.strip().split(" ")
            cur = " " * ind + toks[0]
            for tk in toks[1:]:
                if len(cur) + 1 + len(tk) <= COLS:
                    cur += " " + tk
                else:
                    out.append(cur)
                    cur = " " * (ind + 4) + tk
            out.append(cur)
    return [x.replace("\u00a0", " ") for x in out]


class Tree:
    """the emitted files; `heavy` the modules needing the locked, capped build."""

    def __init__(self, root, T):
        self.root, self.T = root, T
        self.files, self.heavy, self.defs = {}, [], {}

    def mod(self, rel):
        return "KAM.SpinOrbit.Data.%s.Seg.%s" % (self.T, rel.replace("/", "."))

    def write(self, rel, imports, title, doc, body, heavy=False, ns=None):
        ns = ns or "KAM.SpinOrbit.Data.%s" % self.T
        text = HEADER.format(imports="\n".join("public import " + i for i in sorted(set(imports))), title=title,
                             doc=doc, ns=ns, body="\n".join(autowrap(body)).rstrip())
        for i, l in enumerate(text.splitlines()):
            assert len(l) <= COLS, (rel, i, len(l), l)
        assert text.count("\n") <= 1500, (rel, text.count("\n"))
        self.files[rel] = text
        if heavy:
            self.heavy.append(self.mod(rel))
        return self.mod(rel)

    def data(self, stem, title, doc, items, imports):
        """pack (name, lines) items into files `stem NN` of <= MAXLINES lines; records each name's module."""
        files, cur, n = [], [], 0
        for nm, lines in items:
            if cur and n + len(lines) > MAXLINES:
                files.append(cur)
                cur, n = [], 0
            cur.append((nm, lines))
            n += len(lines)
        if cur:
            files.append(cur)
        mods = []
        for fi, f in enumerate(files):
            rel = "%s%02d" % (stem, fi)
            m = self.write(rel, imports + mods[-1:], "%s, part %d" % (title, fi), doc,
                           [l for _, ls in f for l in ls])
            for nm, _ in f:
                self.defs[nm] = m
            mods.append(m)
        return mods

    def save(self):
        base = os.path.join(self.root, "KAM", "SpinOrbit", "Data", self.T, "Seg")
        for rel, text in self.files.items():
            path = os.path.join(base, rel + ".lean")
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w").write(text)
        open(os.path.join(base, "heavy_modules.txt"), "w").write("\n".join(self.heavy) + "\n")


# ---------------------------------------------------------------------------------------------- the emitter
class Emitter:
    def __init__(self, which, gdir, plan, led, root):
        self.w, self.t, self.T = which, which, which.capitalize()
        self.plan, self.led = plan, led
        self.cert = json.load(open(os.path.join(gdir, "%s_cert.json" % which)))
        self.adv = json.load(open(os.path.join(gdir, "%s_advice.json" % which)))
        self.tree = Tree(root, self.T)
        self.base = ["KAM.SpinOrbit.Data.%s.Cert" % self.T, "KAM.SpinOrbit.Data.CsegSupport",
                     "KAM.SpinOrbit.Data.CsegJet"]
        self.W = "base.weight"
        self.pe = "base.piEnc"

    # ------------------------------------------------------------------ names
    def cfgOf(self, chain):
        return "base.cfgFull" if chain in ("cfgFull", "Full") else "base.cfgLow"

    def ck(self, chain):
        return "%s%sCkpt" % (self.t, "Full" if chain == "cfgFull" else "Low")

    def slotName(self, chain, i):
        return "%s%s%d" % (self.t, "F" if chain == "cfgFull" else "L", i)

    def book(self, cfg):
        return self.adv["cfgFull" if cfg == "cfgFull" else "cfgLow"]

    def advRef(self, cfg, fullKey):
        keys = [tuple(k) for k, _ in self.book(cfg)]
        pi = keys.index(tuple(fullKey))
        nm = "advFull" if cfg == "cfgFull" else "advLow"
        adv = self.book(cfg)[pi][1]
        assert adv[0] == "packed", (cfg, fullKey)
        return "%s.p%d" % (nm, pi), adv[1]

    # ------------------------------------------------------------------ ledger and plans (data)
    def emit_ledger(self):
        mods = {}
        for chain in ("cfgFull", "cfgLow"):
            L = self.led["chains"][chain]["ledger"]
            items = [(self.slotName(chain, i), model_defs(self.slotName(chain, i), L[i][0], L[i][1]))
                     for i in sorted(L)]
            mods[chain] = self.tree.data("Ledger%s" % ("Full" if chain == "cfgFull" else "Low"),
                                         "The %s ledger of the %s chain" % (self.w, chain),
                                         "Ledger pairs `(model, cached norm)` (route E; SO-CSPLIT §5).", items,
                                         self.base)
        self.ledger_mods = mods

    def meta_lit(self, chain, b):
        L, nE, nI, cache = self.led["chains"][chain]["metas"][b]
        ents = []
        E = self.charE()
        for k, (poly, r) in cache:
            poly = [(tuple(a), tuple(b)) for a, b in poly]
            if poly == E:
                pt = "(⟨charE⟩ : CertPoly %s)" % TY
            elif poly == self.reflected(E):
                pt = "(⟨charE⟩ : CertPoly %s).reflectSorted" % TY
            else:
                raise SystemExit("cache polynomial is neither the character witness nor its reflection")
            ents.append("(%s, %s, %s)" % (nat_list(k), pt, fixed(r)))
        return "⟨%d, %d, %d, [%s]⟩" % (L, nE, nI, ", ".join(ents))

    @staticmethod
    def reflected(E):
        """`CertPoly.reflectSorted`: the conjugate reflection (key negated, conjugated coefficient), reversed."""
        return [(tuple(-x for x in k), (re, -im)) for k, (re, im) in reversed(E)]

    def charE(self):
        cw = self.cert["wit"]["charWit"]
        return [((int(k[0]), int(k[1])), (int(c[0]), int(c[1]))) for k, c in cw[0][1]["poly"]]

    def emit_plans(self):
        self.plan_mods = {}
        for chain in ("cfgFull", "cfgLow"):
            p = self.plan[chain]
            body = ["/-- The segments of the %s chain. -/" % chain,
                    "def %sSegs : List SegSpec := [" % self.ck(chain)]
            for j, s in enumerate(p["segs"]):
                parts = ["⟨%d, %d, %s, %s, %s⟩%s" % (s["start"], s["stop"], nat_list(s["live"]), nat_list(s["imports"]),
                                                    nat_list(s["exports"]), "," if j + 1 < len(p["segs"]) else "]")]
                body += wrap(parts, "  ") if len(parts[0]) < 96 else self.long_spec(s, j + 1 < len(p["segs"]))
            bounds = [s["start"] for s in p["segs"]] + [p["segs"][-1]["stop"]]
            body += ["", "/-- The boundary metadata. -/", "def %sMetas : List (ComposeMeta %s) := [" % (self.ck(chain), TY)]
            for j, b in enumerate(bounds):
                body += wrap((self.meta_lit(chain, b) + ("," if j + 1 < len(bounds) else "]")).split(" "), "  ")
            body += ["", "/-- The ledger. -/", "def %sLedger : List (ℕ × (CertModel %s × %s)) := [" % (self.ck(chain), TY, TY)]
            led = sorted(self.led["chains"][chain]["ledger"])
            for j, i in enumerate(led):
                nm = self.slotName(chain, i)
                body.append("  (%d, (%s, %sN))%s" % (i, nm, nm, "," if j + 1 < len(led) else "]"))
            body += ["", "/-- The checkpointed %s composition. -/" % chain,
                     "def %s : ComposeCkpt %s := ⟨%sSegs, %sMetas, %sLedger⟩" % (self.ck(chain), TY, self.ck(chain),
                                                                            self.ck(chain), self.ck(chain))]
            rel = "Plan%s" % ("Full" if chain == "cfgFull" else "Low")
            self.plan_mods[chain] = self.tree.write(rel, self.base + self.ledger_mods[chain],
                                                    "The %s plan of the %s chain" % (self.w, chain),
                                                    "Segments, boundary metadata and ledger (untrusted data; "
                                                    "`planOk`/`segOk` check them).", body)

    def long_spec(self, s, comma):
        out = ["  ⟨%d, %d," % (s["start"], s["stop"])]
        for nm in ("live", "imports", "exports"):
            xs = [str(x) for x in s[nm]]
            toks = ["["] if not xs else [("[" if i == 0 else "") + x + ("," if i + 1 < len(xs) else "]") for i, x in
                                          enumerate(xs)]
            if not xs:
                toks = ["[]"]
            toks[-1] += "," if nm != "exports" else ("⟩," if comma else "⟩]")
            out += wrap(toks, "    ")
        return out

    # ------------------------------------------------------------------ the shared op list / segment theorems
    def seg_stmt(self, chain, j):
        return ("%s.segOk 2 soJetLit.prog.ops base.emb base.wit %s %s %s %d = true"
                % (self.ck(chain), self.W, self.cfgOf(chain), self.pe, j))

    def emit_segments(self):
        self.seg_mods = {}
        for chain in ("cfgFull", "cfgLow"):
            mods = []
            sub = "Full" if chain == "cfgFull" else "Low"
            for j, s in enumerate(self.plan[chain]["segs"]):
                nm = "%s%s_seg%d" % (self.t, sub, j)
                if s["forced"]:
                    body = self.forced_segment(chain, j, s, nm)
                    if body is None:
                        continue
                else:
                    body = ["theorem %s :" % nm] + wrap(self.seg_stmt(chain, j).split(" "), "    ")
                    body[-1] += " := by"
                    body += ["  decide +kernel"]
                imps = self.base + [self.plan_mods[chain]] + self.forced_imports.get((chain, j), [])
                mods.append((j, nm, self.tree.write("%s/S%d" % (sub, j), imps, "Segment %d of the %s %s chain"
                                                    % (j, self.w, chain), "One `segOk` (route E, SO-CSPLIT §3.3).",
                                                    body, heavy=True)))
            self.seg_mods[chain] = mods

    forced_imports = {}

    def forced_segment(self, chain, j, s, nm):
        """slot 10 (`.mul`, packed) and the character slot by rewriting (`segOk_one_of`, SO-CSPLIT §3.5)."""
        i = s["start"]
        op = self.led_ops[i]
        C, W, cfg = self.ck(chain), self.W, self.cfgOf(chain)
        seg = "%s.segs[%d]? " % (C, j)
        spec = "(%sSegs.getD %d ⟨0, 0, [], [], []⟩)" % (C, j)
        meta = "(%sMetas.getD %d ⟨0, 0, 0, []⟩)" % (C, j)
        seed = "(ComposeState.seed %s %s %s %s.imports)" % (W, meta, C, spec)
        head = ["theorem %s :" % nm] + wrap(self.seg_stmt(chain, j).split(" "), "    ")
        head[-1] += " := by"
        common = ["  refine ComposeCkpt.segOk_one_of (s := %s)" % spec,
                  "    (m := %s)" % meta,
                  "    (op := %s) (st' := ?st) rfl rfl rfl (by decide +kernel) ?hop ?hres" % self.op_lit(op)]
        if op[0] == "mul":
            a, b = op[1], op[2]
            memo = self.memo_index(chain, (0, i))
            self.forced_imports[(chain, j)] = [self.prod_mod_name(memo)]
            pf = ["  case hop =>",
                  "    rw [shadowStep_of_live 2 base.emb base.wit %s %s %s (by decide +kernel)," % (W, cfg, self.pe),
                  "      composeStep_mul_eq,",
                  "      seed_slot_of_mem %s %s %s (a := %d) (by decide +kernel) (by decide +kernel)," % (W, meta, C, a),
                  "      seed_slot_of_mem %s %s %s (a := %d) (by decide +kernel) (by decide +kernel)," % (W, meta, C, b),
                  "      CertModel.mulN_eq_of_polyProduct %s %s _ _ _ _ _ %s]" % (W, cfg, self.memo_name(memo)),
                  "  case hres =>",
                  "    decide +kernel"]
            return head + common + pf
        if op[0] == "char":
            self.forced_imports[(chain, j)] = [self.char_mod[chain]]
            pf = ["  case hop =>",
                  "    rw [shadowStep_of_live 2 base.emb base.wit %s %s %s (by decide +kernel)," % (W, cfg, self.pe),
                  "      composeStep_char_eq 2 base.emb base.wit %s %s %s %s %s %s_char%s]" % (
                      W, cfg, self.pe, seed, nat_list(op[1]), self.t, "Full" if chain == "cfgFull" else "Low"),
                  "  case hres =>",
                  "    decide +kernel"]
            return head + common + pf
        raise SystemExit("forced segment at an op without a memo route: %r" % (op,))

    def op_lit(self, op):
        t = op[0]
        if t == "mul":
            return "(.mul %d %d)" % (op[1], op[2])
        if t == "add":
            return "(.add %d %d)" % (op[1], op[2])
        if t == "char":
            return "(.char %s)" % nat_list(op[1])
        raise SystemExit("op literal %r" % (op,))

    # ------------------------------------------------------------------ packed products
    def memo_index(self, ctx_chain, fullKey):
        for k, m in enumerate(self.led["memos"]):
            if m["ctx"].startswith(ctx_chain) and tuple(m["fullKey"]) == tuple(fullKey):
                return k
        raise KeyError((ctx_chain, fullKey))

    def memo_name(self, k):
        return "%sM%d" % (self.t, k)

    def prod_mod_name(self, k):
        return self.tree.mod("Prod/M%d" % k)

    def emit_products(self, operand_of):
        """`operand_of(memo)` gives (cfg term, key term, a term, b term, extra imports)."""
        self.prod_done = {}
        self.memo_out = {}
        items = []
        for k, m in enumerate(self.led["memos"]):
            if k not in operand_of:
                continue
            parts = {p["part"]: p for p in m["parts"]}
            ne = [p for p in PART_ORDER if not parts[p]["empty"]]
            assert len(ne) <= 1, "more than one nonempty part: extend the emitter"
            terms = list(m["out"][0]) if m["out"] else []
            items.append(("%sT" % self.memo_name(k), terms_defs(self.memo_name(k) + "T", terms, named=True)[0]))
        self.memo_data = self.tree.data("Memo", "Decoded packed products of the %s torus" % self.w,
                                        "The decoded output of each packed product (L1c (b)).", items, self.base)
        for k, m in enumerate(self.led["memos"]):
            if k not in operand_of:
                continue
            self.emit_product(k, m, *operand_of[k])

    def emit_product(self, k, m, cfg, key, a, b, imps):
        nm = self.memo_name(k)
        cfgname = m["cfg"]
        advname, Pm = self.advRef(cfgname, m["fullKey"])
        assert Pm == P
        parts = {p["part"]: p for p in m["parts"]}
        ne = [p for p in PART_ORDER if not parts[p]["empty"]]
        imps = self.base + self.memo_data + imps
        ma = "(%s.toMants %s.toMant %d)" % (a, cfg, P)
        mb = "(%s.toMants %s.toMant %d)" % (b, cfg, P)
        xy = dict(rr=(".1", ".1"), ii=(".2", ".2"), ri=(".1", ".2"), ir=(".2", ".1"))
        tname = nm + "T"
        _, texpr = terms_defs(tname, list(m["out"][0]) if m["out"] else [])
        if ne:
            p = ne[0]
            adv = "%s.%s" % (advname, p)
            X = "((%s.getD ([], []))%s)" % (ma, xy[p][0])
            Y = "((%s.getD ([], []))%s)" % (mb, xy[p][1])
            ea = "(%s.la.slotTerms %s)" % (adv, X)
            eb = "(%s.lb.slotTerms %s)" % (adv, Y)
            sh = ["theorem %s_shards :" % nm] + wrap(("%s.shardRange.all (checkShardAt %s %s %s) = true := by"
                                                      % (adv, adv, ea, eb)).split(" "), "    ") + ["  decide +kernel"]
            self.tree.write("Prod/M%dSh" % k, imps, "Packed product %d: shards" % k,
                            "The shard group of one packed product (L1c (a)).", sh, heavy=True)
            f = "(fun v => ⟨v, ofInt 0⟩)" if p in ("rr", "ii") else "(fun v => ⟨ofInt 0, v⟩)"
            # exactly the form `mulPacked_eq_of_parts` expects (`pXX.1` of the explicit pair), so the application
            # needs no unfolding (design R5)
            pair = "(%s.targetTerms, %s.remainderBound %s (2 * %d)).1" % (adv, adv, self.W, P)
            src = "(%s)" % pair if p != "ii" else "((%s).map fun t => (t.1, -t.2))" % pair
            dec = ["theorem %s_dec :" % nm] + wrap(("dyadicTerms (2 * %d) %s.scale %s %s = some %s :="
                                                    % (P, adv, f, src, tname)).split(" "), "    ")
            dec += ["  eq_some_of_termsBeq_cseg (by decide +kernel)"]
            self.tree.write("Prod/M%dDec" % k, imps, "Packed product %d: decode" % k,
                            "The decode of one packed product (L1c (b)).", dec, heavy=True)
        # assembly. Every Boolean side check is its OWN theorem (a statement of closed terms, its own
        # heartbeat budget): nested `decide`s inside one declaration share one budget (design signal)
        body, auxn = [], [0]

        def aux(stmt):
            nmA = "%sA%d" % (nm, auxn[0])
            auxn[0] += 1
            body.extend(["theorem %s :" % nmA] + wrap((stmt + " := by").split(" "), "    ") + ["  decide +kernel", ""])
            return nmA
        hparts, tparts, rems = {}, {}, {}
        for p in PART_ORDER:
            advp = "%s.%s" % (advname, p)
            X = "((%s.getD ([], []))%s)" % (ma, xy[p][0])
            Y = "((%s.getD ([], []))%s)" % (mb, xy[p][1])
            if p in ne:
                hx = aux("%s.isEmpty = false" % X)
                hy = aux("%s.isEmpty = false" % Y)
                hla = aux("%s.la.allSlots %s = true" % (advp, X))
                hlb = aux("%s.lb.allSlots %s = true" % (advp, Y))
