"""SO-CSEG-GEN: emit the Lean modules of the segmented proof of one N = 65 torus (untrusted tooling; the kernel
checks everything).

    python3 -B csplit_emit.py lower|upper GENDIR PLAN.json LEDGER.pkl OUTROOT [--only PARTS]

Design: docs/tracks/SO/design/SO-CSPLIT.md §3 (M0-M3), §5 (ledger), §6 (build order). Everything is written under
OUTROOT/KAM/SpinOrbit/Data/<Torus>/Seg/ (plus the shared jet under OUTROOT/KAM/SpinOrbit/Data/CsegJet*.lean), with
`heavy_modules.txt` (the modules whose kernel work must be built one at a time under the probe lock and the 10 GB
cap, `csplit_kbuild.sh`) beside them.

Every generated proof is an EXPLICIT application (design R5: no `apply … <;> assumption`, no `simp` over landed
bodies): `decide +kernel` closes only Boolean checks on closed terms, and lemma applications carry every argument.
No heartbeat or depth option is ever written.

Modules (per torus, prefix `t` = lower/upper):
  Seg/Ledger{Full,Low}NN    the ledger pairs `tF{i}`/`tL{i}` (model, cached norm) of the two chains   (data)
  Seg/Plan{Full,Low}        `tFullCkpt`, `tLowCkpt : ComposeCkpt SoBackendV2`                         (data)
  Seg/Memo NN               decoded packed products and operand mantissas                           (data)
  Seg/Stage NN              Gram / BG / torsion stage literals                                      (data)
  Seg/Full/S{j}, Low/S{j}   one segment `segOk … j = true` (forced one-op segments by rewriting)   (heavy)
  Seg/Prod/M{k}Sh, M{k}Dec  one packed product: its shards, its decode                              (heavy)
  Seg/Prod/M{k}             the product equation `polyProduct … = some …` (assembly; operand work)  (heavy)
  Seg/Gram/*, Seg/Tors/*    stage entries and stages                                                (heavy)
  Seg/Chain, Seg/Checks     the `compose_eq` instances and the landed sub-check Bools              (light/heavy)
"""
