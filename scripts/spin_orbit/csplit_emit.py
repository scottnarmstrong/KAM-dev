    # ------------------------------------------------------------------ operands of every memo
    def operands(self):
        """memo index -> (cfg, key, a, b, imports), each a closed Lean term; the dead cfgLow slot-10 product is
        skipped (the shadow run never evaluates it)."""
        out = {}
        W, pe = self.W, self.pe
        ch = self.led["char"]
        for k, m in enumerate(self.led["memos"]):
            ctx, fk = m["ctx"], tuple(m["fullKey"])
            if ctx.startswith("cfg"):
                chain = ctx.split("/")[0]
                slot = int(ctx.split("slot")[1])
                live = set(self.plan[chain]["live"]) | {i for i, o in enumerate(self.led_ops) if o[0] == "char"}
                if slot not in live:
                    continue
                cfg = self.cfgOf(chain)
                if fk[0] == 0:                        # the program's packed product (slot 10)
                    j = self.seg_of(chain, slot)
                    s = self.plan[chain]["segs"][j]
                    C = self.ck(chain)
                    meta = "(%sMetas.getD %d ⟨0, 0, 0, []⟩)" % (C, j)
                    spec = "(%sSegs.getD %d ⟨0, 0, [], [], []⟩)" % (C, j)
                    key = "[0, (ComposeState.seed %s %s %s %s.imports).len]" % (W, meta, C, spec)
                    a, b = self.led_ops[slot][1], self.led_ops[slot][2]
                    out[k] = (cfg, key, "(%s.slotPair %s %d).1.poly" % (C, W, a),
                              "(%s.slotPair %s %d).1.poly" % (C, W, b), [self.plan_mods[chain]])
                else:                                 # the character witness residuals [1, j]
                    c = ch[chain]
                    cfgw = "(%s.forWitness 1 (base.wit.expWit.length + %d))" % (cfg, c["cidx"])
                    j = fk[2]
                    g = "(charPhaseModel 2 base.emb %s %s %s)" % (W, pe, nat_list(c["k2"]))
                    out[k] = (cfgw, "[1, %d]" % j, "(itemsPoly (%s.poly.terms.filterMap (derivItem %d)))" % (g, j),
                              "(⟨charE⟩ : CertPoly %s).negP" % TY, [])
            elif ctx.startswith("gram"):
                cfg = "base.cfgLow"
                if fk[1] == 0:
                    _, _, a_, b_, r = fk
                    f = lambda x: ("(dkAngleModel 2 base.emb %s %s %d %d)" % (W, pe, r, x) if r < 2 else
                                   "(dkActionModel 2 base.emb %s %s %d %d)" % (W, pe, r - 2, x))
                    out[k] = (cfg, "[3, 0, %d, %d, %d]" % (a_, b_, r), f(a_) + ".poly", f(b_) + ".poly", [])
                else:
                    _, _, i, j, kk = fk
                    out[k] = (cfg, "[3, 1, %d, %d, %d]" % (i, j, kk),
                              "(⟨0, gramInvPoly base.gramInv %d %d, ofInt 0⟩ : CertModel %s).poly" % (i, kk, TY),
                              "(modelMatrixEntry %sGm %d %d).poly" % (self.t, kk, j), [self.stage_mod])
            else:                                     # torsion [4, s, i, j, k]
                _, s, i, j, kk = fk
                A, B_ = self.stage_operands(s)
                out[k] = ("base.cfgLow", "([4, %d] ++ [%d, %d, %d])" % (s, i, j, kk),
                          "(modelMatrixEntry %s %d %d).poly" % (A, i, kk), "(modelMatrixEntry %s %d %d).poly" % (B_, kk, j),
                          [self.stage_mod])
        return out

    def seg_of(self, chain, slot):
        for j, s in enumerate(self.plan[chain]["segs"]):
            if s["start"] <= slot < s["stop"]:
                return j
        raise KeyError(slot)

