#!/usr/bin/env python3
"""LOCK-DATA: the light and site-sharded v2 core checks of the lock certificate (untrusted tooling).

Writes under KAM/SpinOrbit/Data/LockN65/:
  Site{s}{D,B}.lean   one certified bite each (`siteOk … = true`, `decide +kernel`; heavy)
  Core.lean           `lock_core : refinedCore 2 params freqBox refinedWit = true` by `refinedCore_of`, the
                      sites by `sitesOk_of` (certified ones from Site*, classical ones decided here)

    python3 lock_checks_lean.py [ROOT]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sofx_lean as SL     # noqa: E402
import lock_lean as LL     # noqa: E402
import lock_bites as LB    # noqa: E402

GEN = "Generated by `scripts/spin_orbit/lock_checks_lean.py`. Do not edit."
OPENS = "KAM.Certificate KAM.CertificateSharp.V2"
Q = "lockQ"


def site_stmt(s, side):
    fn, cf, pr = (("δ", "c", "1") if side == "d" else ("b", "cbar", "2"))
    return ["siteOk %s.n %s.τ refinedWit.core.J freqBox refinedWit.κ" % (Q, Q),
            "      params.γ"
            + " (%s.%s %d) (%s.%s.getD %d 0)" % (Q, fn, s, Q, cf, s),
            "      (refinedWit.sites.getD %d (none, none)).%s = true" % (s, pr)]


def main(root):
    tree = LL.LockTree(root, "LockN65")
    tree.write("Num", [tree.module("Params"), tree.module("Witness")],
               "The rational data of the lock's v2 run (generated)", GEN, ["/-- The numbers of the refined run (`RefinedWit.num`). -/",
                     "def lockQ : NumQ := refinedWit.num 2 params freqBox"], opens=OPENS)
    light = [tree.module("Num")]
    mods = {}
    for s in range(LB.KP):
        for side in ("d", "b"):
            if (side, s) not in LB.BITES:
                continue
            nm = "lock_site_%s%d" % (side, s)
            st = site_stmt(s, side)
            body = ["/-- The certified bite at `%s_%d` (one kernel computation). -/" % (
                "δ" if side == "d" else "b", s), "theorem %s :" % nm, "    " + st[0]] + ["  " + x for x in st[1:]]
            body[-1] += " := by"
            body += ["  decide +kernel"]
            rel = "Site%d%s" % (s, side.upper())
            tree.write(rel, light, "Certified bite `%s%d` (generated; heavy)" % (side, s), GEN, body, opens=OPENS)
            mods[(side, s)] = nm
    pf = []
    for side in ("d", "b"):
        pass

    def comp(side, s):
        if (side, s) in mods:
            return mods[(side, s)]
        return "(by decide +kernel)"

    body = ["/-- The v2 core test of the lock (route A refined, kp = %d), sharded by sites. -/" % LB.KP,
            "theorem lock_core : refinedCore 2 params freqBox refinedWit = true :=",
            "  refinedCore_of (by decide +kernel) (by decide +kernel) (by decide +kernel)",
            "    (sitesOk_of fun s hs => by",
            "      have hs : s < %d := hs" % LB.KP,
            "      match s, hs with"]
    for s in range(LB.KP):
        body += ["      | %d, _ => exact ⟨%s, %s⟩" % (s, comp("d", s), comp("b", s))]
    body += ["      | _ + %d, h => absurd h (by omega))" % LB.KP,
             "    (by decide +kernel) (by decide +kernel)"]
    tree.write("Core", light + [tree.module(r) for r in sorted(
        "Site%d%s" % (s, side.upper()) for (side, s) in mods)], "The lock v2 core test (generated)", GEN, body,
        opens=OPENS)
    for rel, text in tree.files.items():
        with open(tree.path(rel), "w") as f:
            f.write(text)
    print(len(tree.files), "files")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", ".."))
