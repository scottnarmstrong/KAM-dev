#!/usr/bin/env python3
"""LOCK-DATA: the literal jet of the lock certificate's Hamiltonian `.mul (.const c) (lockHamExpr (8/65)
lunarLockCentre)` (c = 1000001/1000000; 3158 ops) as Lean data, and the bridge `lock_jet` (SO-CSPLIT M0, decided by
`HamJet.eq_of_segBeq`).  The ops come from lock_jet.py, the mirror of the landed compiler (checked op for op by the
SO-LOCK-COST gate, G1b; the bridge re-checks it in the kernel).  Untrusted tooling.

    python3 lock_jet_lean.py [ROOT]
"""
import os
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sofx_lean as SL    # noqa: E402
import lock_sofx as LS    # noqa: E402
import lock_jet as LJ     # noqa: E402

C = F(1000001, 1000000)
PER = 1300


def q(x):
    x = F(x)
    return "%d / %d" % (x.numerator, x.denominator) if x.denominator != 1 else str(x.numerator)


def nat_list(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def op_lit(op):
    t = op[0]
    if t == "const":
        return ".const (%s : ℚ) (%s : ℚ) (%d)" % (q(op[1]), q(op[2]), int(op[3]))
    if t == "action":
        return ".action %d" % op[1]
    if t == "char":
        return ".char %s" % nat_list(op[1])
    if t in ("add", "mul"):
        return ".%s %d %d" % (t, op[1], op[2])
    return ".%s %d" % (t, op[1])


def main(root):
    J = LJ.jet(2, ("mul", ("const", C), LS.LH.lock_ham_expr(LS.OMEGA, LS.CS)))
    ops = [op_lit(LJ.norm_op(o)) for o in J["prog"]]
    assert len(ops) == 3158, len(ops)
    tree = SL.Tree(root, "LockN65")
    mods, names = [], []
    for fi, s in enumerate(range(0, len(ops), PER)):
        ch = ops[s:s + PER]
        nm = "jetOps%d" % fi
        body = ["/-- Operations `%d … %d` of the jet program. -/" % (s, s + len(ch) - 1),
                "def %s : List SlpOp := [" % nm] + ["  " + x + ("," if i + 1 < len(ch) else "]")
                                                   for i, x in enumerate(ch)]
        tree.write("JetOps%d" % fi, ["KAM.Certificate.Expr.Slp"], "Lock jet operations, part %d (generated)" % fi,
                   "Generated by `scripts/spin_orbit/lock_jet_lean.py`. Do not edit.", body)
        mods.append(tree.module("JetOps%d" % fi))
        names.append(nm)
    tab = lambda xs: "[" + ", ".join(nat_list(x) for x in xs) + "]"
    d3 = "[" + ", ".join(tab(row) for row in J["d3"]) + "]"
    body = ["/-- The Hamiltonian's time scale `c = κ s` (`κ = 1`, `s = 1000001/1000000`). -/",
            "def hamScale : ℚ := %s" % q(C), "",
            "/-- The certificate's Hamiltonian. -/",
            "def lockHam : HamExpr 2 := .mul (.const hamScale) (lockHamExpr (8 / 65) lunarLockCentre)", "",
            "/-- The %d operations of the jet program (`lock_jet.py`, the compiler mirror). -/" % len(ops),
            "def lockJetOps : List SlpOp := %s" % " ++ ".join(names), "",
            "/-- The jet: the program and its index tables. -/", "def lockJetLit : HamJet where",
            "  prog := ⟨lockJetOps⟩", "  v0 := %d" % J["v0"]]
    body += SL.row_lines(["d1 := %s" % nat_list(J["d1"])], "  ")
    body += SL.row_lines(["d2 :=", tab(J["d2"])], "  ")
    body += SL.row_lines(["d3 :="] + [t + " " for t in d3.split(" ")], "  ")
    tree.write("Jet", mods + ["KAM.SpinOrbit.Lock.Coords.HamExpr"], "The literal jet of the lock Hamiltonian (generated)",
               "`lockJetLit`: the compiled jet of `lockHam` as data (SO-CSPLIT M0).\n"
               "Generated by `scripts/spin_orbit/lock_jet_lean.py`. Do not edit.", body,
               opens="KAM.Certificate KAM.SpinOrbit.Lock")
    body = ["/-- The compiled jet equals the literal (M0; decided once; heavy, about 3.5 GB in the gate). -/",
            "theorem lock_jet : lockHam.jet = lockJetLit :=", "  HamJet.eq_of_segBeq (by decide +kernel)"]
    tree.write("JetEq", [tree.module("Jet"), "KAM.CertificateSharp.Kernel.SegDefs"], "The lock jet bridge (generated)",
               "`lock_jet`: the compiled jet of `lockHam` equals `lockJetLit`.\n"
               "Generated by `scripts/spin_orbit/lock_jet_lean.py`. Do not edit.", body,
               opens="KAM.Certificate KAM.CertificateSharp KAM.SpinOrbit.Lock")
    for rel, text in tree.files.items():
        with open(tree.path(rel), "w") as f:
            f.write(text)
    print(len(tree.files), "files")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", ".."))
