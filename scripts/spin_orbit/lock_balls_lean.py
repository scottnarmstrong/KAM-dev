#!/usr/bin/env python3
"""LOCK-DATA: the disc pass of the lock certificate split into three kernel segments (BallChain.lean).

Writes under KAM/SpinOrbit/Data/LockN65/:
  Domain.lean            lockWH, lockCentre, lockRadius, lockTaylor (the certificate's domain; light)
  BallsCk{1,2,3}*.lean   the reversed ball states after 1300, 2600 and 3158 slots (toy_arith's Slp.balls mirror,
                         bit-exact against Lean on the gate's G2 checkpoint)
  HamSeg{0,1,2}.lean     `segOk … = true` by `decide +kernel` (heavy; one theorem each)
  HamBalls.lean          `lock_balls : Slp.balls 2 lockJetLit.prog … = some ck3.reverse` (assembly; light)

    SO_LOCK_DATA=... SO_LOCK_SIZE=... python3 lock_balls_lean.py GENDIR [ROOT]
"""
import os
import pickle
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.set_int_max_str_digits(0)
import sofx_lean as SL      # noqa: E402
import lock_lean as LL      # noqa: E402
import lock_gen as LG       # noqa: E402
import lock_jet_lean as LJL  # noqa: E402
import lock_jet as LJ       # noqa: E402
import lock_sofx as LS      # noqa: E402
import toy_arith as TA      # noqa: E402

SL.FORMAT = "KAM.SpinOrbit.Data.LockN65.Format"
GEN = "Generated by `scripts/spin_orbit/lock_balls_lean.py`. Do not edit."
CUTS = (1300, 2600)


def ball_row(b):
    (re, im), r = b
    parts = []
    for i, q in enumerate((re, im, r)):
        ls = SL.rat_lit(q)
        pre = ("(⟨" if i == 0 else ("" if i == 1 else ""))
        post = ("," if i == 0 else ("⟩," if i == 1 else ")"))
        ls = [pre + ls[0]] + ls[1:]
        ls[-1] += post
        parts += ls
    return SL.row_lines(parts, "  ") if all(len(p) < 80 for p in parts) else ["  " + p for p in parts]


def main(gdir, root):
    g = pickle.load(open(os.path.join(gdir, "gen.pkl"), "rb"))
    dom = g["domain"]
    rhoH, wH = F(dom["rhoH"]), F(dom["wH"])
    centre, radius = [F(x) for x in dom["centre"]], [F(x) for x in dom["radius"]]
    J = LJ.jet(2, ("mul", ("const", LJL.C), LS.LH.lock_ham_expr(LS.OMEGA, LS.CS)))
    ops = LG.toy_ops([LJ.norm_op(o) for o in J["prog"]])
    bs = TA.slp_balls(2, ops, wH, centre, radius, 30)
    assert bs is not None and len(bs) == 3158
    tree = LL.LockTree(root, "LockN65")
    body = ["/-- The certificate's domain weight `(ρ_H, w_H)`. -/", "def lockWH : CertWeight :="]
    body += ["  ⟨" + SL.rat_lit(rhoH)[0] + ","] + ["   " + l for l in SL.rat_lit(wH)] + ["  ⟩"]
    body += ["", "def lockCentre : List ℚ := [%s]" % ", ".join(SL.rat_lit(x)[0] for x in centre),
             "", "def lockRadius : List ℚ := [%s]" % ", ".join(SL.rat_lit(x)[0] for x in radius),
             "", "/-- The Taylor order of the exponential balls (`expOrder`). -/", "def lockTaylor : ℕ := 30"]
    tree.write("Domain", [SL.FORMAT], "The domain of the lock certificate (generated)",
               "Weight, action centres and radii of `D = T_{ρ_H} × polydisc(centre, radius)`.\n" + GEN, body)
    cks = []
    for j, cut in enumerate(CUTS + (3158,)):
        st = list(reversed(bs[:cut]))
        nm = "ck%d" % (j + 1)
        cks.append(SL.emit_blob(tree, nm, "List (CC ℚ × ℚ)", [ball_row(b) for b in st],
                                "Disc-pass state after %d slots (reversed)" % cut))
    segs = [("jetOps0", 0, "[]", "ck1"), ("jetOps1", CUTS[0], "ck1", "ck2"), ("jetOps2", CUTS[1], "ck2", "ck3")]
    for i, (o, k, rin, rout) in enumerate(segs):
        imps = [tree.module("Domain"), tree.module("JetOps%d" % i), "KAM.SpinOrbit.Data.LockN65.BallChain"]
        imps += [m for m in cks if m.endswith(rin.capitalize()) or m.endswith(rout.capitalize())]
        body = ["/-- Disc-pass segment %d (slots `%d …`), one kernel computation. -/" % (i, k),
                "theorem hamSeg%d : segOk 2 lockWH lockCentre lockRadius lockTaylor %d %s %s %s = true := by" % (
                    i, k, rin, o, rout), "  decide +kernel"]
        tree.write("HamSeg%d" % i, imps, "Disc-pass segment %d (generated; heavy)" % i, GEN, body)
    body = ["/-- The whole disc pass of the certificate's program, from the three segments. -/",
            "theorem lock_balls :",
            "    Slp.balls 2 lockJetLit.prog lockWH lockCentre lockRadius lockTaylor = some ck3.reverse :=",
            "  balls_eq_of_segs (k₁ := %d) (k₂ := %d) (by decide +kernel) (by decide +kernel)" % CUTS,
            "    hamSeg0 hamSeg1 hamSeg2"]
    tree.write("HamBalls", [tree.module("HamSeg%d" % i) for i in range(3)] + [tree.module("Jet")],
               "The lock disc pass (generated)", "Assembled from `HamSeg0`–`HamSeg2` by `balls_eq_of_segs`.\n" + GEN,
               body)
    for rel, text in tree.files.items():
        with open(tree.path(rel), "w") as f:
            f.write(text)
    print(len(tree.files), "files", sum(len(t.encode()) for t in tree.files.values()), "bytes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", ".."))
